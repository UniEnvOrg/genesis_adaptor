"""Build the FR3 + Sharpa Wave MJCFs (one per hand side) from the models in ``unienv_genesis_collection/assets``.

Writes ``franka_fr3_sharpa/fr3_sharpa_left.xml`` and ``fr3_sharpa_right.xml``: the FR3 arm of
``franka_fr3_hand/fr3_hand.xml`` with its Franka Hand replaced by ``sharpa_wave/<side>_hand.xml`` (mujoco_menagerie).

* **Names.** The model's side prefix is dropped (``index_PP``, ``thumb_CMC_FE`` ...), so both sides have the same
  names; its default classes and materials get a ``sharpa_`` prefix (the FR3's use ``visual``, ``collision`` ...).
* **Mount.** On the back of the hand: the palm's back face (5 cm thick) on the FR3 flange through a 5 mm adapter, the palm
  facing along the flange axis, the fingers along the Franka Hand's x axis (the flange turned -45 deg). A flange pointing
  down holds the palm down with the fingers level, and the palm face sits 5.5 cm past the flange.
* **Palm frame.** A ``palm`` body on the hand's root at the centre of the four finger bases, with the root's axes: +x out
  of the palm (the side the fingers curl to), +z along the fingers (the Wuji / Allegro / LEAP convention).

The robot class is :class:`~unienv_genesis_collection.robots.franka_fr3_sharpa.FrankaFR3WithSharpa`; a bimanual setup is
two of them.

Run from the repository root:  python scripts/build_fr3_sharpa_mjcf.py
"""

from __future__ import annotations

import copy
import pathlib
import xml.etree.ElementTree as ET

import numpy as np

ROBOTS = pathlib.Path(__file__).resolve().parents[1] / "unienv_genesis_collection" / "assets" / "robots"

FLANGE_Z = 0.107
ADAPTER = 0.005
#: The mount point on the hand: the middle of the palm's back face, in the hand's root frame.
PALM_BACK = np.array([-0.025, 0.0, 0.05])
FR3_HOME = "0 0 0 -1.57079 0 1.57079 -0.7853"
PREFIX = "sharpa_"
_NAMED = ("name", "joint", "joint1", "joint2", "body1", "body2", "mesh", "site")


def _quat(R: np.ndarray) -> np.ndarray:
    w = np.sqrt(max(0.0, 1 + R[0, 0] + R[1, 1] + R[2, 2])) / 2
    x = np.copysign(np.sqrt(max(0.0, 1 + R[0, 0] - R[1, 1] - R[2, 2])) / 2, R[2, 1] - R[1, 2])
    y = np.copysign(np.sqrt(max(0.0, 1 - R[0, 0] + R[1, 1] - R[2, 2])) / 2, R[0, 2] - R[2, 0])
    z = np.copysign(np.sqrt(max(0.0, 1 - R[0, 0] - R[1, 1] + R[2, 2])) / 2, R[1, 0] - R[0, 1])
    q = np.array([w, x, y, z])
    return q / np.linalg.norm(q)


def _rename(root: ET.Element, side: str) -> None:
    """Drop the side prefix from every name and reference; prefix default classes and materials."""
    for e in root.iter():
        for attr in _NAMED:
            value = e.get(attr)
            if value is not None and value.startswith(f"{side}_"):
                e.set(attr, value[len(side) + 1:])
        for attr in ("class", "childclass", "material"):
            if e.get(attr) is not None:
                e.set(attr, PREFIX + e.get(attr))
        if e.tag == "material" and e.get("name") is not None:
            e.set("name", PREFIX + e.get("name"))


def build(side: str) -> pathlib.Path:
    src = ET.parse(ROBOTS / "franka_fr3_hand" / "fr3_hand.xml").getroot()
    hand = ET.parse(ROBOTS / "sharpa_wave" / f"{side}_hand.xml").getroot()
    mesh_dir = hand.find("compiler").get("meshdir")
    _rename(hand, side)

    root = ET.Element("mujoco", model=f"fr3_sharpa_{side}")
    root.append(ET.Comment(" Generated by scripts/build_fr3_sharpa_mjcf.py; do not edit by hand. "))
    ET.SubElement(root, "compiler", angle="radian", autolimits="true")
    ET.SubElement(root, "option", integrator="implicitfast")
    default = copy.deepcopy(src.find("default"))
    for d in list(default):  # keep the FR3 arm classes, drop the Franka Hand's
        if d.get("class") == "hand":
            default.remove(d)
    default.append(copy.deepcopy(hand.find("default").find("default")))
    root.append(default)
    asset = ET.SubElement(root, "asset")
    for m in src.find("asset"):
        if isinstance(m.tag, str) and not ((m.tag == "mesh" and "franka_emika_panda" in m.get("file", "")) or m.get("name", "").startswith("hand_")):
            asset.append(copy.deepcopy(m))
    for m in hand.find("asset"):
        c = copy.deepcopy(m)
        if c.tag == "mesh":
            c.set("file", f"../sharpa_wave/{mesh_dir}{c.get('file')}")
        asset.append(c)

    world = ET.SubElement(root, "worldbody")
    arm = copy.deepcopy(src.find("worldbody").find("body"))
    link7 = next(b for b in arm.iter("body") if b.get("name") == "fr3_link7")
    link7.remove(next(b for b in link7 if b.tag == "body" and b.get("name") == "hand"))
    palm_root = copy.deepcopy(hand.find("worldbody").find("body"))
    # Hand root axes in link7: x along the flange axis, z along the Franka Hand's x (link7 x turned -45 deg about z).
    c = np.sqrt(0.5)
    R = np.stack([[0.0, 0.0, 1.0], [-c, -c, 0.0], [c, -c, 0.0]], axis=1)
    pos = np.array([0.0, 0.0, FLANGE_Z + ADAPTER]) - R @ PALM_BACK
    palm_root.set("pos", " ".join(f"{v:.6g}" for v in pos))
    palm_root.set("quat", " ".join(f"{v:.6g}" for v in _quat(R)))
    # The palm frame: centre of the finger bases.
    bases = {b.get("name"): [float(v) for v in b.get("pos").split()] for b in palm_root.findall("body")}
    centre = np.mean([bases[k] for k in ("index_MCP_VL", "middle_MCP_VL", "ring_MCP_VL", "pinky_MC")], axis=0)
    palm = ET.Element("body", name="palm", pos=" ".join(f"{v:.6g}" for v in centre))
    palm_root.append(palm)
    link7.append(palm_root)
    world.append(arm)

    act = ET.SubElement(root, "actuator")
    act.extend(copy.deepcopy(a) for a in src.find("actuator") if isinstance(a.tag, str) and a.get("joint", "").startswith("fr3_"))
    act.extend(copy.deepcopy(a) for a in hand.find("actuator"))
    con = ET.SubElement(root, "contact")
    ET.SubElement(con, "exclude", body1="fr3_link0", body2="fr3_link1")
    ET.SubElement(con, "exclude", body1="fr3_link7", body2="hand_C_MC")
    ET.SubElement(con, "exclude", body1="fr3_link6", body2="hand_C_MC")
    con.extend(copy.deepcopy(e) for e in hand.find("contact"))
    n_hand = sum(1 for _ in palm_root.iter("joint"))
    ET.SubElement(ET.SubElement(root, "keyframe"), "key", name="home", qpos=f"{FR3_HOME} {' '.join(['0'] * n_hand)}")
    path = ROBOTS / "franka_fr3_sharpa" / f"fr3_sharpa_{side}.xml"
    path.parent.mkdir(parents=True, exist_ok=True)
    ET.indent(root, space="  ")
    ET.ElementTree(root).write(path, encoding="unicode")
    return path


if __name__ == "__main__":
    for s in ("left", "right"):
        print(build(s))
