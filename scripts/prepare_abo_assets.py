def _strip_dimensions(clause: str) -> str:
    """Strip measurements from one clause (``""`` when it carried nothing else).

    Dimension bullets are common in ABO listings and can occupy whole clauses
    (``67"W x 38"D x 35"H``); a clause left as a bare ``label:`` is dropped
    with them.
    """
    stripped = _MEASURE_RANGE_RE.sub(" ", clause)
    stripped = _MEASURE_SEQ_RE.sub(" ", stripped)
    stripped = _UNIT_MEASURE_RE.sub(" ", stripped)
    if not stripped.strip(" ,;:-–—"):
        return ""
    if stripped.strip().endswith((":", "=")):
        return ""
    return stripped


def clean_annotation(text: str) -> str:
    """Normalize one listings string into a language annotation.

    Strips HTML, drops parenthesised/bracketed qualifiers and measurement
    strings (``87"W x 37.75''D``, ``3.8 to 6-Foot``), collapses the whitespace
    and punctuation the removals leave behind, lowercases and caps the result
    at :data:`_MAX_ANNOTATION_LENGTH` characters on a word boundary.  Returns
    ``""`` when nothing descriptive is left.
    """
    if not text:
        return ""
    text = html.unescape(_HTML_TAG_RE.sub(" ", str(text)))
    text = re.sub(r"\([^)]*\)|\[[^\]]*\]", " ", text)
    # An opening bracket can be left unmatched when its closing half was part
    # of the dropped text; truncate there (GSO's annotation_from_description).
    text = re.split(r"[([]", text)[0]
    clauses = [
        kept.strip(" ,;:-–—")
        for kept in (_strip_dimensions(clause) for clause in re.split(r"[;\n]+", text))
        if kept.strip(" ,;:-–—")
    ]
    text = "; ".join(clauses)
    text = text.lower()
    # Inch/feet marks the measurement patterns did not consume (e.g. after a
    # number separated from its unit: ``39.5'' Diameter``).
    text = re.sub(r"(?<=\d)\s*[\"']{1,2}", " ", text)
    # Collapse the gaps the removals left behind ("kitchen table, , oak").
    text = re.sub(r"\s*([,;:])(?:\s*[,;:])+", r"\1", text)
    text = re.sub(r"\s*[-–—]\s*(?=[,;:])", "", text)
    # A dangling dimension separator ("39.5 diameter x").
    text = re.sub(r"\s+[x×*](?=\s*[,;:.]|$)", " ", text)
    text = re.sub(r"\s+", " ", text)
    text = re.sub(r"\s+([.,;:!?])", r"\1", text)
    text = text.strip(" ,;:-–—|/\t")
    if len(text) > _MAX_ANNOTATION_LENGTH:
        text = text[:_MAX_ANNOTATION_LENGTH].rsplit(" ", 1)[0]
        text = text.strip(" ,;:-–—|/")
    return text


def normalize_tag(text: str) -> str:
    """Normalize a category name to a tag (``"Speakers & Subwoofers"`` →
    ``"speakers_subwoofers"``)."""
    return re.sub(r"[^a-z0-9]+", "_", str(text or "").lower()).strip("_")


def _append_unique(annotations: List[str], text: str) -> None:
    if text and text not in annotations:
        annotations.append(text)


def node_leaf_names(value: Any) -> List[str]:
    """Leaf names of the listings catalog-node paths, e.g.
    ``"/Products/Live Sound & Stage/Speaker Stands"`` → ``"Speaker Stands"``."""
    leaves = []
    for entry in value or []:
        if not isinstance(entry, dict):
            continue
        name = entry.get("node_name") or ""
        leaf = name.rstrip("/").rsplit("/", 1)[-1].strip()
        if leaf:
            leaves.append(leaf)
    return leaves


def build_catalog_entry(
    object_id: str,
    record: Optional[Mapping[str, Any]],
    *,
    graspable: bool = False,
) -> dict:
    """Build one catalog entry (annotations broad → detailed, plus tags).

    The annotations are the normalized product type (broad), the catalog-node
    leaves, the cleaned ``item_name`` and up to
    :data:`_MAX_BULLET_ANNOTATIONS` cleaned ``bullet_point``s (detailed).  The
    tags are the normalized product type and node leaves, plus
    ``box_gripper_graspable`` when *graspable*.  Objects without a listing (or
    without a usable name) fall back to a generic + id-derived annotation.
    """
    record = record or {}
    annotations: List[str] = []
    tags: Set[str] = set()

    for product_type in _english_values(record.get("product_type")):
        tag = normalize_tag(product_type)
        if tag:
            tags.add(tag)
            _append_unique(annotations, tag.replace("_", " "))
    for leaf in node_leaf_names(record.get("node")):
        tag = normalize_tag(leaf)
        if tag:
            tags.add(tag)
            _append_unique(annotations, leaf.lower())

    cleaned_name = clean_annotation(localized_value(record.get("item_name")) or "")
    _append_unique(annotations, cleaned_name)
    for bullet in _english_values(record.get("bullet_point"))[:_MAX_BULLET_ANNOTATIONS]:
        _append_unique(annotations, clean_annotation(bullet))

    if not annotations:
        annotations = ["object", f"product {object_id.lower()}"]
    if graspable:
        tags.add(GRASPABLE_TAG)
    return {"language_annotations": annotations, "tags": sorted(tags)}


def build_catalog_records(
    model_ids: Sequence[str],
    listings: Mapping[str, Mapping[str, Any]],
    graspable_ids: Iterable[str],
) -> List[dict]:
    """Return the shared-catalog records (``object_id`` + ``catalog_entry``)."""
    graspable = set(graspable_ids)
    return [
        {
            "object_id": object_id,
            "catalog_entry": build_catalog_entry(
                object_id, listings.get(object_id), graspable=object_id in graspable,
            ),
        }
        for object_id in sorted(model_ids)
    ]


def write_catalog(out_root: Path, records: Sequence[dict], merge: bool = True) -> int:
    """Write ``catalog.json`` through the shared catalog writer.

    Incremental runs merge: entries of objects this run did not touch are kept,
    while a re-packaged object rewrites its own entry.
    """
    n_graspable = sum(
        1 for record in records if GRASPABLE_TAG in record["catalog_entry"]["tags"]
    )
    return _write_catalog_impl(
        out_root, records, merge=merge,
        summary_label=f"{n_graspable} {GRASPABLE_TAG}",
    )


