def select_object_ids(
    model_index: Mapping[str, Any],
    *,
    objects: Optional[str] = None,
    limit: Optional[int] = None,
) -> List[str]:
    """Resolve the ids to package: explicit ``--objects`` or the first *limit*.

    Ids are returned sorted so catalog entries and progress output are
    deterministic.
    """
    if objects and limit is not None:
        raise ValueError("Pass either --objects or --limit, not both.")
    if objects:
        ids = sorted({part.strip() for part in objects.split(",") if part.strip()})
        unknown = [object_id for object_id in ids if object_id not in model_index]
        if unknown:
            raise ValueError(
                f"Unknown ABO object id(s): {', '.join(unknown)} "
                f"(the dataset has {len(model_index)} modelled objects)."
            )
        if not ids:
            raise ValueError("--objects did not name any id.")
        return ids
    ids = sorted(model_index)
    if limit is not None:
        if limit <= 0:
            raise ValueError("--limit must be positive.")
        ids = ids[:limit]
    return ids


def package_object(
    object_id: str,
    model_row: Mapping[str, str],
    out_root: Path,
    *,
    keep_glb: bool = False,
) -> Tuple[bool, List[float], float]:
    """Download one ABO model and write its self-contained object directory.

    Returns ``(graspable, mesh extents, max relative extent deviation)``; the
    directory is built in a sibling temp directory and swapped in atomically so
    an interrupted run cannot leave a half-written object behind.  The GLB is
    streamed into that temp directory (never kept in the metadata cache; the
    full dataset is ~154 GB) and dropped again unless *keep_glb*.
    """
    obj_dir = out_root / object_id
    tmp_dir = out_root / f".{object_id}.tmp"
    if tmp_dir.exists():
        shutil.rmtree(tmp_dir)
    if obj_dir.exists():
        # Resume support: a completed object dir from an earlier (interrupted)
        # run is reused as-is.  Graspability is recomputed from the converted
        # mesh on disk (the GLB is not re-downloaded) so the label merge and
        # the catalog stay correct.
        extents = mesh_extents_from_obj(obj_dir / "model.obj")
        return min(extents) < GRIPPER_WIDTH, extents, 0.0
    tmp_dir.mkdir(parents=True)
    try:
        glb_file = _download(
            _MODEL_KEY.format(path=model_row["path"]), tmp_dir / "model.glb",
        )
        glb_bytes = glb_file.read_bytes()
        if not keep_glb:
            glb_file.unlink()
        extents = convert_glb_to_zup_obj(glb_bytes, tmp_dir)
    except Exception:
        shutil.rmtree(tmp_dir, ignore_errors=True)
        raise

    if obj_dir.exists():
        shutil.rmtree(obj_dir)
    tmp_dir.rename(obj_dir)
    return min(extents) < GRIPPER_WIDTH, extents, _relative_extent_error(model_row, extents)


def merge_graspable(ids: Iterable[str], path: Path = _GRASPABLE_CACHE) -> Set[str]:
    """Union *ids* into the checked-in graspable list and return the union.

    Every run contributes the objects it actually measured (a ``--limit`` run
    extends the bake; the full run completes it), so the file is never
    speculative.
    """
    known: Set[str] = set()
    if path.is_file():
        known = set(json.loads(path.read_text()))
    merged = known | set(ids)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(sorted(merged), indent=1) + "\n")
    return merged


# Objects handed to each worker process before its pool is recycled (i.e. the
# workers exit and fresh ones take over).  Bounds how much memory even a buggy
# retainer — allocator arenas, trimesh/PIL caches, reference cycles awaiting
# the generational GC — can accumulate in a worker before an exit wipes it.
_TASKS_PER_WORKER_EPOCH = 32


def _package_task(
    task: Tuple[str, Mapping[str, str], str, bool],
) -> Tuple[str, Optional[Tuple[bool, List[float], float]], Optional[str]]:
    """Worker-process entry point for :func:`package_object` (picklable).

    Returns ``(object_id, result, error)`` with exactly one of the last two
    set.  The error is flattened to a string here so an unpicklable exception
    cannot take the parent's failure reporting down with it.
    """
    object_id, model_row, out_root, keep_glb = task
    try:
        result = package_object(
            object_id, model_row, Path(out_root), keep_glb=keep_glb,
        )
        return object_id, result, None
    except Exception as error:  # noqa: BLE001 — reported per object
        return object_id, None, f"{type(error).__name__}: {error}"


def _package_all(
    out_root: Path,
    model_index: Mapping[str, Mapping[str, str]],
    model_ids: Sequence[str],
    *,
    keep_glb: bool,
    workers: int,
) -> Tuple[Dict[str, Tuple[bool, List[float], float]], Dict[str, str]]:
    """Package every id, collecting per-object failures instead of aborting.

    The work runs in worker *processes*, in batches: each batch gets a fresh
    :class:`ProcessPoolExecutor` and the pool is shut down (which joins — i.e.
    exits — its workers) before the next batch starts.  That is the memory
    guarantee: the trimesh load/convert transiently allocates hundreds of MB
    per object and neither trimesh/numpy nor the C allocator's per-thread
    arenas give all of it back, so a long-lived worker (or, as before, a
    thread pool) ratchets RSS by a few MB per object until the kernel
    OOM-kills the run — the observed failure was the resume scan over the
    ~4,900 existing objects climbing past 12 GB (a re-run of the same phase
    peaked at 9.7 GB after 3,200 objects, still climbing).  A process exit
    returns every byte, so the parent stays small regardless of how many
    objects are processed.

    A batch size of ``workers * _TASKS_PER_WORKER_EPOCH`` keeps the respawn
    cost (fork: milliseconds; spawn platforms: a module import) amortized
    while bounding what one worker can accumulate between exits.
    """
    results: Dict[str, Tuple[bool, List[float], float]] = {}
    failures: Dict[str, str] = {}

    worker_count = max(1, workers)
    batch_size = worker_count * _TASKS_PER_WORKER_EPOCH
    done = 0

    def _record(
        object_id: str,
        outcome: Optional[Tuple[bool, List[float], float]],
        error: Optional[str],
    ) -> None:
        nonlocal done
        done += 1
        if error is not None:
            failures[object_id] = error
            print(f"WARNING: failed to package {object_id}: {error}")
        else:
            results[object_id] = outcome  # type: ignore[assignment]
        if done % 25 == 0 or done == len(model_ids):
            print(f"  ... packaged {done}/{len(model_ids)}")

    for start in range(0, len(model_ids), batch_size):
        batch = model_ids[start:start + batch_size]
        tasks = [
            (object_id, model_index[object_id], str(out_root), keep_glb)
            for object_id in batch
        ]
        consumed = 0
        try:
            # `with` shuts the pool down and joins the workers, so the next
            # batch starts from fresh processes (memory handed back to the OS).
            with ProcessPoolExecutor(max_workers=worker_count) as executor:
                for object_id, outcome, error in executor.map(_package_task, tasks):
                    consumed += 1
                    _record(object_id, outcome, error)
        except BrokenExecutor as error:
            # A worker died (e.g. the kernel killed it on a huge model); the
            # objects it swallowed are failures, the rest of the run continues
            # in a fresh pool (the thread-based code lost the whole run here).
            for object_id in batch[consumed:]:
                _record(object_id, None, f"worker process died: {error}")
    return results, failures


def write_provenance(out_root: Path, license_text: str) -> None:
    """Ship ``LICENSE`` (verbatim CC BY 4.0 text) and the provenance ``README.md``."""
    (out_root / "LICENSE").write_text(license_text)
    (out_root / "README.md").write_text(PROVENANCE_README)


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--output-dir", type=Path, required=True,
        help="Directory to place the prepared 'objects/abo' tree in.",
    )
    parser.add_argument(
        "--objects", default=None,
        help="Comma-separated object ids (3dmodel_id) to package. Mutually "
             "exclusive with --limit.",
    )
    parser.add_argument(
        "--limit", type=int, default=None,
        help="Package only the first N objects (sorted ids) — for incremental "
             "and test runs; a full run omits it.",
    )
    parser.add_argument(
        "--cache-dir", type=Path, default=Path(tempfile.gettempdir()) / "abo_dataset_cache",
        help="Cache for the dataset metadata (models CSV + listings shards). "
             "Defaults to a directory in the system temp dir.",
    )
    parser.add_argument(
        "--refresh-metadata", action="store_true",
        help="Re-download the cached models CSV / listings shards.",
    )
    parser.add_argument(
        "--license-file", type=Path, default=None,
        help="Local copy of the bucket's LICENSE-CC-BY-4.0.txt. Downloaded "
             "verbatim from the bucket when omitted.",
    )
    parser.add_argument(
        "--keep-glb", action="store_true",
        help="Also ship the original model.glb next to the converted OBJ "
             "(roughly doubles the uploaded tree; off by default).",
    )
    parser.add_argument("--workers", type=int, default=4)
    args = parser.parse_args(argv)

    cache_dir = args.cache_dir.expanduser().resolve()
    model_index = load_model_index(
        cache_dir, refresh=args.refresh_metadata,
    )
    model_ids = select_object_ids(
        model_index, objects=args.objects, limit=args.limit,
    )
    print(f"Selected {len(model_ids)} of {len(model_index)} modelled objects.")
    listings = find_listing_records(
        cache_dir, model_ids, refresh=args.refresh_metadata,
    )
    missing_listings = [object_id for object_id in model_ids if object_id not in listings]
    if missing_listings:
        print(f"WARNING: no listings metadata for {len(missing_listings)} object(s); "
              f"falling back to id-derived annotations "
              f"(e.g. {', '.join(missing_listings[:3])})")

    out_root = args.output_dir.expanduser().resolve() / "objects" / "abo"
    results, failures = _package_all(
        out_root, model_index, model_ids,
        keep_glb=args.keep_glb, workers=args.workers,
    )

    # Graspability is measured on the meshes just converted; merge into the
    # checked-in list (the mechanism ``compute_graspable.py abo`` re-bakes).
    graspable = merge_graspable(
        [object_id for object_id, (g, _, _) in results.items() if g],
    )
    deviations = [d for _, (_, _, d) in results.items()]
    if deviations:
        print(f"Mesh extents match 3dmodels.csv within "
              f"{100.0 * max(deviations):.3f}% (metric scale check).")

    license_text = (
        Path(args.license_file).expanduser().read_text()
        if args.license_file is not None
        else _download(_LICENSE_KEY, out_root / "LICENSE").read_text()
    )
    write_provenance(out_root, license_text)

    packaged = [object_id for object_id in model_ids if object_id in results]
    records = build_catalog_records(packaged, listings, graspable)
    write_catalog(out_root, records)
    print(f"Wrote {len(packaged)} object directories in {out_root} "
          f"({len(graspable)} {GRASPABLE_TAG} ids checked in so far).")
    if failures:
        print(f"FAILED to package {len(failures)} object(s): "
              f"{', '.join(sorted(failures)[:10])}")

    print(
        "\nTo upload (requires write access to the org):\n"
        f"  hf upload UniEnvOrg/unienv_genesis_collection_assets \\\n"
        f"      {out_root} objects/abo --repo-type dataset\n"
        "Note: the box_gripper_graspable tag is only complete after a full "
        "(no --limit/--objects) run, which also downloads all 7953 GLBs "
        "(~154 GB)."
    )
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
