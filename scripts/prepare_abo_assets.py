#!/usr/bin/env python3
"""Prepare Amazon Berkeley Objects (ABO) assets for the collection's assets repo.

Downloads (lazily, one model at a time) from the public ABO bucket
`https://amazon-berkeley-objects.s3.amazonaws.com/` and repackages the 7953
modelled objects into the self-contained per-object layout expected by
``unienv_genesis_collection.objects.hub_objects.abo_object``::

    <output>/objects/abo/LICENSE          # verbatim LICENSE-CC-BY-4.0.txt
    <output>/objects/abo/README.md        # provenance + Amazon.com attribution
    <output>/objects/abo/catalog.json     # generated annotations + tags
    <output>/objects/abo/<id>/model.obj   # Z-up visual mesh
    <output>/objects/abo/<id>/material.mtl
    <output>/objects/abo/<id>/texture.png
    <output>/objects/abo/<id>/model.glb   # original GLB (only with --keep-glb)

ABO models are glTF 2.0 binary (GLB), **Y-up**, metric (metres), with the
product standing on the ``Y=0`` plane.  Genesis applies its own Y-up → Z-up
conversion to GLB files, which would desync the trimesh-based bounding-box
path that ``ABOObject`` inherits (trimesh does no such conversion).  This
script therefore bakes the rotation into the shipped mesh — the exact
``(X, Y, Z) → (X, -Z, Y)`` mapping Genesis applies to Y-up formats (a +90°
rotation about X) — and exports ``model.obj``, so the Z-up OBJ needs no
morph-side transform and the mesh frame, the bounding-box frame and the
placed frame agree.

The OBJ's texture is renamed to ``texture.png`` (trimesh names it after the
GLB material, which for ABO is an opaque identifier that can even carry the
literal quotes of the glTF material name) and the ``model.obj`` /
``material.mtl`` references are rewritten to match, mirroring the YCB
packager.  Only the base-colour image survives the OBJ conversion (the
normal / metallic-roughness maps the GLB carries are dropped); the few models
that ship no image resources get a generated neutral ``texture.png`` so every
object directory stays uniform.

The catalog is generated by joining ``3dmodels/metadata/3dmodels.csv.gz``
with the listings metadata (``listings/metadata/listings_<shard>.json.gz``):
per object, language annotations run broad → detailed (product type, catalog
node, cleaned ``item_name``, cleaned ``bullet_point``s) and tags carry the
normalized product type + catalog node leaf, plus ``box_gripper_graspable``
for objects whose smallest mesh extent fits the ~8.5 cm gripper width.  A
model id may appear under several listings: the first ``en_US`` one wins,
otherwise the first occurrence (deterministic shard order).  The graspability
label is computed inline from the mesh already in hand and merged into the
checked-in ``scripts/data/abo_graspable.json`` (consumed by this script), so
an incremental run extends the bake and a full run completes it.

Usage::

    # small incremental run (repeatable; catalog entries merge)
    python scripts/prepare_abo_assets.py --output-dir /tmp/abo_assets --limit 25
    python scripts/prepare_abo_assets.py --output-dir /tmp/abo_assets \\
        --objects B075QFCHM9,B07B7H9VMM

    # full run: all 7953 models (~154 GB of downloads; the prepared tree is
    # of the same order of magnitude — the OBJ conversion drops the normal /
    # metallic-roughness maps but rewrites the base-colour image)
    python scripts/prepare_abo_assets.py --output-dir /tmp/abo_assets --workers 8

``--workers`` sizes a pool of short-lived worker **processes** (not threads):
the per-object trimesh load/convert allocates hundreds of MB transiently —
the largest ABO OBJs are ~1 GB — and neither trimesh/numpy nor glibc's
per-thread arenas return it reliably, so a long run inside one process
ratchets RSS by a few MB per object until the kernel OOM-kills it (observed:
the resume scan over ~4,900 existing objects climbed to >12 GB).  Each batch
of objects is therefore handled by a fresh pool whose exit returns *all*
retained memory to the OS, whatever trimesh/numpy kept alive; the parent
process only handles small metadata and the catalog.

Then upload to the Hub (needs write access to the org)::

    hf upload UniEnvOrg/unienv_genesis_collection_assets \\
        /tmp/abo_assets/objects/abo objects/abo --repo-type dataset

Licence: ABO was relicensed to **CC BY 4.0** by Amazon.com (the earlier
CC BY-NC 4.0 record is stale); ``LICENSE`` is the bucket's verbatim
``LICENSE-CC-BY-4.0.txt``.
"""

