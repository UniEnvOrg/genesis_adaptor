def _download(key: str, dest: Path, *, timeout: float = _FETCH_TIMEOUT) -> Path:
    """Stream ``S3_BASE/<key>`` into *dest* (atomically via a ``.part`` file)."""
    dest.parent.mkdir(parents=True, exist_ok=True)
    tmp = dest.with_name(dest.name + ".part")
    with urllib.request.urlopen(f"{S3_BASE}/{key}", timeout=timeout) as response:
        with open(tmp, "wb") as out:
            shutil.copyfileobj(response, out)
    tmp.replace(dest)
    return dest


def cached_resource(cache_dir: Path, key: str, *, refresh: bool = False) -> Path:
    """Return the local copy of the S3 object *key*, downloading it once.

    The dataset metadata (the models CSV and the 16 listings shards, ~85 MB)
    is cached in *cache_dir* so repeat runs — and the per-object downloads,
    which reuse the same listing scan — pay for it only once.
    """
    local = cache_dir / key
    if refresh or not local.is_file():
        print(f"Fetching {S3_BASE}/{key} ...")
        _download(key, local)
    return local


def load_model_index(cache_dir: Path, *, refresh: bool = False) -> Dict[str, Dict[str, str]]:
    """Return ``{3dmodel_id: csv row}`` from ``3dmodels.csv.gz``.

    The row carries the model's ``path`` (relative to ``3dmodels/original/``,
    with a shard letter that is *not* derivable from the id), its metric mesh
    extents (``extent_x/y/z``, metres) and its mesh statistics.
    """
    path = cached_resource(cache_dir, _MODELS_CSV_KEY, refresh=refresh)
    index: Dict[str, Dict[str, str]] = {}
    with gzip.open(path, "rt", newline="", encoding="utf-8") as handle:
        for row in csv.DictReader(handle):
            index[row["3dmodel_id"]] = row
    if not index:
        raise ValueError(f"No models found in {path}")
    return index


def iter_listings(shard_file: Path) -> Iterator[dict]:
    """Yield the JSON records of one gzip-compressed listings shard."""
    with gzip.open(shard_file, "rt", encoding="utf-8") as handle:
        for line in handle:
            yield json.loads(line)


def _entries(value: Any) -> List[dict]:
    """Normalize a listings field to a list of ``{language_tag, value}`` dicts."""
    if value is None:
        return []
    if isinstance(value, dict):
        return [value]
    return [entry for entry in value if isinstance(entry, dict)]


def localized_value(value: Any) -> Optional[str]:
    """First ``en_US`` entry of a language-tagged listings field, else ``en_*``.

    Listings are multilingual (the ``en_US`` entry is often *not* the first);
    values without any English entry fall back to the first occurrence so no
    object is left without metadata.
    """
    entries = _entries(value)
    for entry in entries:
        if entry.get("language_tag") == "en_US":
            return entry.get("value")
    for entry in entries:
        if str(entry.get("language_tag") or "").startswith("en"):
            return entry.get("value")
    return entries[0].get("value") if entries else None


def _english_values(value: Any) -> List[str]:
    """All English values of a language-tagged listings field, in order."""
    english = [
        entry.get("value")
        for entry in _entries(value)
        if str(entry.get("language_tag") or "").startswith("en")
    ]
    if english:
        return [text for text in english if text]
    first = localized_value(value)
    return [first] if first else []


def _has_english_name(record: Mapping[str, Any]) -> bool:
    return any(
        entry.get("language_tag") == "en_US"
        for entry in _entries(record.get("item_name"))
    )


def find_listing_records(
    cache_dir: Path,
    wanted: Sequence[str],
    *,
    refresh: bool = False,
) -> Dict[str, dict]:
    """Return the listing record chosen for each of *wanted* (model ids).

    Shards are scanned in :data:`LISTINGS_SHARDS` order and the scan stops as
    soon as every wanted id has an ``en_US`` listing.  A model id that appears
    under several listings/domains resolves to the first ``en_US`` one, else to
    the first occurrence — deterministic either way.
    """
    wanted_set = set(wanted)
    english: Dict[str, dict] = {}
    fallback: Dict[str, dict] = {}
    for shard in LISTINGS_SHARDS:
        shard_file = cached_resource(
            cache_dir, _LISTINGS_KEY.format(shard=shard), refresh=refresh,
        )
        for record in iter_listings(shard_file):
            model_id = record.get("3dmodel_id")
            if model_id is None or model_id not in wanted_set:
                continue
            fallback.setdefault(model_id, record)
            if model_id not in english and _has_english_name(record):
                english[model_id] = record
        if len(english) == len(wanted_set):
            break
        print(f"  ... scanned shard {shard}: "
              f"{len(english)}/{len(wanted_set)} ids have en_US metadata")
    return {
        model_id: english.get(model_id, fallback[model_id])
        for model_id in wanted
        if model_id in english or model_id in fallback
    }


