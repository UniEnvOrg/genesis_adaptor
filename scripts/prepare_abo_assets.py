def _single_mesh(scene: Any) -> Any:
    """Flatten a loaded GLB scene to one mesh (ABO models are single-mesh)."""
    import trimesh

    if not isinstance(scene, trimesh.Scene):
        return scene
    if not len(scene.geometry):
        raise ValueError("GLB contains no geometry")
    if hasattr(scene, "to_geometry"):  # trimesh >= 4
        return scene.to_geometry()
    return scene.dump(concatenate=True)


def _base_color(mesh: Any) -> Tuple[int, int, int]:
    """The mesh material's base colour as 8-bit RGB (neutral grey if absent)."""
    import numpy as np

    material = getattr(getattr(mesh, "visual", None), "material", None)
    for attribute in ("baseColorFactor", "diffuse"):
        factor = getattr(material, attribute, None) if material is not None else None
        if factor is None:
            continue
        rgb = np.asarray(factor, dtype=float).reshape(-1)[:3]
        if rgb.size == 3 and rgb.max() > 1.0:
            rgb = rgb / 255.0
        if rgb.size == 3:
            color = tuple(int(round(c * 255)) for c in np.clip(rgb, 0.0, 1.0))
            # trimesh substitutes a magenta "error" material for geometry that
            # carries no material at all; the placeholder stays neutral there.
            return _NEUTRAL_GREY if color == (255, 0, 255) else color
    return _NEUTRAL_GREY


def _placeholder_texture(texture: Path, color: Tuple[int, int, int]) -> None:
    """Write a flat *color* ``texture.png`` (models that ship no image)."""
    from PIL import Image

    Image.new("RGB", (4, 4), color=color).save(texture)


def rewrite_texture_references(obj_dir: Path, *, base_color: Tuple[int, int, int] = (102, 102, 102)) -> Path:
    """Normalize the OBJ's texture to ``texture.png`` and rewrite its references.

    trimesh names the exported image after the GLB material — for ABO an opaque
    identifier that may even keep the literal quotes of the glTF material name
    (``"APKM...".png``) — so the first (base-colour) image is renamed to
    ``texture.png`` and the ``model.obj`` / ``material.mtl`` references are
    rewritten to match.  Additional material images get a deterministic
    ``texture_<n>.png`` name for the same reason, and a model without any
    exported image gets a flat *base_color* placeholder so the per-object
    layout stays uniform.
    """
    images = sorted(
        path for path in obj_dir.iterdir()
        if path.is_file()
        and path.suffix.lower() in _IMAGE_SUFFIXES
        and path.name != TEXTURE_NAME
    )
    texture = obj_dir / TEXTURE_NAME
    for index, image in enumerate(images):
        new_name = TEXTURE_NAME if index == 0 else f"texture_{index}{image.suffix}"
        # The exported name can carry quotes; both forms appear in the
        # references trimesh writes.
        variants = {image.name, image.name.replace('"', "").replace("'", "")}
        image.rename(obj_dir / new_name)
        for reference in ("model.obj", "material.mtl"):
            reference_file = obj_dir / reference
            if not reference_file.is_file():
                continue
            text = reference_file.read_text()
            for variant in sorted(variants, key=len, reverse=True):
                text = text.replace(variant, new_name)
            reference_file.write_text(text)

    if not images:
        _placeholder_texture(texture, base_color)

    material_file = obj_dir / "material.mtl"
    if not material_file.is_file():
        # Some materials-less GLBs export an OBJ without any material at all;
        # keep the per-object layout uniform (and `_required_files` complete).
        material_file.write_text(
            "# Generated for models that ship no material.\n"
            "newmtl material_0\n"
            "Kd 0.40000000 0.40000000 0.40000000\n"
            f"map_Kd {TEXTURE_NAME}\n"
        )
        obj_file = obj_dir / "model.obj"
        text = obj_file.read_text()
        additions = []
        if "mtllib" not in text:
            additions.append(f"mtllib {material_file.name}")
        if "usemtl" not in text:
            additions.append("usemtl material_0")
        if additions:
            block = "\n".join(additions)
            if re.search(r"(?m)^o ", text):
                text = re.sub(
                    r"(?m)^(o .*)$", lambda m: f"{m.group(1)}\n{block}", text, count=1,
                )
            else:
                text = f"{block}\n{text}"
            obj_file.write_text(text)
    else:
        text = material_file.read_text()
        if TEXTURE_NAME not in text:
            separator = "" if not text or text.endswith("\n") else "\n"
            with material_file.open("a") as handle:
                handle.write(f"{separator}map_Kd {TEXTURE_NAME}\n")
    return texture


def convert_glb_to_zup_obj(glb_bytes: bytes, obj_dir: Path) -> List[float]:
    """Export a Y-up ABO GLB into a Z-up ``model.obj`` (+ material + texture).

    The Y-up → Z-up rotation is baked into the mesh — the same
    ``(X, Y, Z) → (X, -Z, Y)`` mapping Genesis applies to Y-up formats — so the
    OBJ needs no morph-side transform and the trimesh bounding-box path agrees
    with the placed frame.  Returns the mesh extents (metres) after conversion.
    """
    import trimesh

    obj_dir.mkdir(parents=True, exist_ok=True)
    scene = trimesh.load(io.BytesIO(glb_bytes), file_type="glb")
    mesh = _single_mesh(scene)
    mesh.apply_transform(
        trimesh.transformations.rotation_matrix(math.pi / 2.0, [1.0, 0.0, 0.0])
    )

    out_scene = trimesh.Scene()
    out_scene.add_geometry(mesh, node_name="abo", geom_name="model")
    out_scene.export(obj_dir / "model.obj")
    rewrite_texture_references(obj_dir, base_color=_base_color(mesh))
    return [float(extent) for extent in mesh.extents]


def mesh_extents_from_obj(obj_file: Path) -> List[float]:
    """Return the (x, y, z) extents of an already-converted ``model.obj``.

    Used for resume support: the mesh on disk is already Z-up, so a plain
    trimesh load yields the same extents the conversion reported originally —
    no GLB re-download and no extra transform.
    """
    import trimesh

    mesh = _single_mesh(trimesh.load(str(obj_file), file_type="obj"))
    return [float(extent) for extent in mesh.extents]


def _relative_extent_error(row: Mapping[str, str], extents: Sequence[float]) -> float:
    """Max relative deviation between the mesh extents and the CSV's (metres)."""
    try:
        expected = sorted(float(row[axis]) for axis in ("extent_x", "extent_y", "extent_z"))
    except (KeyError, TypeError, ValueError):
        return 0.0
    actual = sorted(extents)
    return max(
        abs(a - e) / e if e else 0.0
        for a, e in zip(actual, expected)
    )


