#!/usr/bin/env python3
"""Prepare Google Scanned Objects assets for the Hugging Face assets repo.

Clones (or reuses) `kevinzakka/mujoco_scanned_objects
<https://github.com/kevinzakka/mujoco_scanned_objects>`_ — MJCF models for
the 1030 objects of Google's Scanned Objects dataset — and repackages it
into the layout expected by
``unienv_genesis_collection.objects.hub_objects.gso_object``::

    <output>/objects/gso/LICENSE          # upstream MIT license (MJCF files)
    <output>/objects/gso/README.md        # provenance + CC-BY 4.0 attribution
    <output>/objects/gso/catalog.json     # generated annotations + tags
    <output>/objects/gso/<id>/model.xml            # upstream MJCF, verbatim
    <output>/objects/gso/<id>/model_freejoint.xml  # generated movable variant
    <output>/objects/gso/<id>/model.obj  (+ texture.png, model_collision_*.obj)

The upstream ``model.xml`` body has no joint, which welds it to the world in
MuJoCo/Genesis.  For each object this script generates a
``model_freejoint.xml`` variant with a ``<freejoint/>`` injected, which
``GSOObject`` loads for movable objects (the pristine ``model.xml`` is kept
for ``fixed=True``).

It also writes ``<output>/objects/gso/catalog.json`` — per-object language
annotations (broad category terms → detailed product description) and tags:
the normalized category labels from the original dataset's metadata on
Gazebo Fuel (https://fuel.gazebosim.org, owner ``GoogleResearch``), plus a
``box_gripper_graspable`` tag for objects in the checked-in
``scripts/data/gso_graspable.json`` (regenerate with
``scripts/compute_graspable.py gso``).  The Fuel metadata comes from the
checked-in cache under ``scripts/data/``; deleting that file (or pointing
``--fuel-metadata`` elsewhere) re-fetches it from the Fuel API (~1030 calls).

Usage::

    python scripts/prepare_gso_assets.py --output-dir /tmp/gso_assets
    # or with an existing clone (possibly a sparse checkout):
    python scripts/prepare_gso_assets.py --source ~/mujoco_scanned_objects \
        --output-dir /tmp/gso_assets

Then upload to the Hub (needs write access to the org)::

    hf upload UniEnvOrg/unienv_genesis_collection_assets \
        /tmp/gso_assets/objects/gso objects/gso --repo-type dataset

Note the full dataset is ~1 GB.
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess
import sys
import tempfile
import urllib.parse
import urllib.request
import xml.etree.ElementTree as ET
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

UPSTREAM_REPO_URL = "https://github.com/kevinzakka/mujoco_scanned_objects.git"
FUEL_MODEL_URL = "https://fuel.gazebosim.org/1.0/GoogleResearch/models/{name}"

# Checked-in cache of the Gazebo Fuel metadata (descriptions + categories).
_FUEL_METADATA_CACHE = Path(__file__).parent / "data" / "gso_fuel_metadata.json"

# Checked-in list of box-gripper-graspable object ids, produced by
# ``scripts/compute_graspable.py`` (smallest mesh bbox dimension < gripper width).
_GRASPABLE_CACHE = Path(__file__).parent / "data" / "gso_graspable.json"
GRASPABLE_TAG = "box_gripper_graspable"

# Broad language-annotation terms per category tag.  Together with the
# detailed product description these give annotations spanning broad →
# detailed (e.g. ["toy", "action figure", "schleich lion action figure"]).
CATEGORY_ANNOTATIONS = {
    "action_figures": ("toy", "action figure"),
    "bag": ("bag",),
    "board_games": ("board game",),
    "bottles_and_cans_and_cups": ("container",),
    "camera": ("camera",),
    "car_seat": ("car seat",),
    "consumer_goods": ("household item",),
    "hat": ("hat",),
    "headphones": ("headphones",),
    "keyboard": ("keyboard",),
    "legos": ("building toy", "lego set"),
    "media_cases": ("media case",),
    "mouse": ("computer mouse",),
    "shoe": ("shoe",),
    "stuffed_toys": ("toy", "stuffed toy"),
    "toys": ("toy",),
}

PROVENANCE_README = """\
# Google Scanned Objects (MJCF)

Repackaged from
[kevinzakka/mujoco_scanned_objects](https://github.com/kevinzakka/mujoco_scanned_objects):
MJCF models for the 1030 household objects of Google's
[Scanned Objects dataset](https://arxiv.org/abs/2204.11918), with V-HACD
convex collision decompositions generated by
[obj2mjcf](https://github.com/kevinzakka/obj2mjcf).

Licensing follows upstream: the 3D assets (`.obj`, `.png`) are licensed under
[CC-BY 4.0](https://creativecommons.org/licenses/by/4.0/) by Google LLC; the
MJCF (`.xml`) files are MIT licensed (see `LICENSE`).

Each object additionally carries a generated `model_freejoint.xml` — a copy
of the upstream `model.xml` with a `<freejoint/>` injected so the object is
movable (the upstream file's jointless body is welded to the world).
Generated by `genesis_adaptor/scripts/prepare_gso_assets.py`.

When using these models, please cite:

> L. Downs, A. Francis, N. Koenig, B. Kinman, R. Hickman, K. Reymann,
> T. B. McHugh, V. Vanhoucke, "Google Scanned Objects: A High-Quality
> Dataset of 3D Scanned Household Items", ICRA 2022.
"""


def inject_freejoint(xml_text: str) -> str:
    """Return MJCF text with a ``<freejoint/>`` injected into the root body.

    The upstream models have exactly one body under ``<worldbody>`` and no
    joints; the freejoint is inserted as its first child.
    """
    root = ET.fromstring(xml_text)
    bodies = root.findall("./worldbody/body")
    if len(bodies) != 1:
        raise ValueError(
            f"Expected exactly one root body, found {len(bodies)}."
        )
    body = bodies[0]
    if any(child.tag in ("joint", "freejoint") for child in body):
        raise ValueError("Root body already has a joint.")
    body.insert(0, ET.Element("freejoint", {"name": "freejoint"}))
    ET.indent(root)
    return ET.tostring(root, encoding="unicode")


def _clone_upstream(dest: Path) -> Path:
    print(f"Cloning {UPSTREAM_REPO_URL} into {dest} (~1 GB) ...")
    subprocess.run(
        ["git", "clone", "--depth", "1", UPSTREAM_REPO_URL, str(dest)],
        check=True,
    )
    return dest


def _verify_object_dir(obj_out_dir: Path) -> None:
    """Check that every file referenced by both MJCF variants exists."""
    for xml_name in ("model.xml", "model_freejoint.xml"):
        root = ET.parse(obj_out_dir / xml_name).getroot()
        for element in root.iter():
            ref = element.get("file")
            if ref and not (obj_out_dir / ref).is_file():
                raise FileNotFoundError(
                    f"{obj_out_dir.name}/{xml_name} references missing file: {ref}"
                )


def prepare(source: Path, output_dir: Path) -> tuple[Path, list[str]]:
    models_src = source / "models"
    if not models_src.is_dir():
        raise FileNotFoundError(f"No 'models' directory in source: {source}")

    out_root = output_dir / "objects" / "gso"
    out_root.mkdir(parents=True, exist_ok=True)

    object_ids = sorted(p.name for p in models_src.iterdir() if p.is_dir())
    if not object_ids:
        raise FileNotFoundError(f"No object directories found in {models_src}")

    for i, object_id in enumerate(object_ids):
        obj_out_dir = out_root / object_id
        obj_out_dir.mkdir(exist_ok=True)

        for f in sorted((models_src / object_id).iterdir()):
            if f.is_file():
                shutil.copy2(f, obj_out_dir / f.name)

        model_xml = obj_out_dir / "model.xml"
        if not model_xml.is_file():
            raise FileNotFoundError(f"Missing {model_xml}")
        (obj_out_dir / "model_freejoint.xml").write_text(
            inject_freejoint(model_xml.read_text())
        )

        _verify_object_dir(obj_out_dir)
        if (i + 1) % 100 == 0:
            print(f"  ... {i + 1}/{len(object_ids)}")

    shutil.copy2(source / "LICENSE", out_root / "LICENSE")
    (out_root / "README.md").write_text(PROVENANCE_README)

    print(f"Prepared {len(object_ids)} objects in {out_root}")
    return out_root, object_ids


def annotation_from_description(object_id: str, description: str) -> str:
    """Derive a language annotation from a Fuel product description.

    Takes the first line, drops bracketed/parenthesised qualifiers
    (e.g. ``"[Nintendo 3DS]"``), collapses whitespace and lowercases.
    Falls back to an id-derived annotation when the result is empty.
    """
    text = description.splitlines()[0] if description else ""
    text = re.sub(r"\([^)]*\)|\[[^\]]*\]", " ", text)
    # An opening bracket can be left unmatched when its closing half sat on
    # a dropped line; truncate there.
    text = re.split(r"[([]", text)[0]
    text = re.sub(r"\s+", " ", text).strip(" ,;:-")
    if not text:
        text = " ".join(object_id.split("_"))
    return text.lower()


def tag_from_category(category: str) -> str:
    """Normalize a Fuel category name to a tag (``"Media Cases"`` → ``"media_cases"``)."""
    return re.sub(r"[^a-z0-9]+", "_", category.lower()).strip("_")


def fetch_fuel_metadata(object_ids: list[str]) -> dict:
    """Fetch ``{id: {"description": ..., "categories": [...]}}`` from Gazebo Fuel."""

    def fetch(object_id: str) -> tuple[str, dict]:
        url = FUEL_MODEL_URL.format(name=urllib.parse.quote(object_id))
        with urllib.request.urlopen(url, timeout=30) as response:
            data = json.load(response)
        return object_id, {
            "description": data.get("description", ""),
            "categories": data.get("categories") or [],
        }

    metadata = {}
    with ThreadPoolExecutor(max_workers=12) as executor:
        for i, (object_id, meta) in enumerate(executor.map(fetch, object_ids)):
            metadata[object_id] = meta
            if (i + 1) % 200 == 0:
                print(f"  ... fetched {i + 1}/{len(object_ids)}")
    return metadata


def _load_graspable_ids() -> set:
    """Load the checked-in set of box-gripper-graspable object ids."""
    if _GRASPABLE_CACHE.is_file():
        return set(json.loads(_GRASPABLE_CACHE.read_text()))
    print(f"WARNING: {_GRASPABLE_CACHE} missing; no {GRASPABLE_TAG} tags applied. "
          f"Run scripts/compute_graspable.py gso to generate it.")
    return set()


def build_catalog(
    object_ids: list[str], metadata: dict, graspable_ids: set | None = None,
) -> dict:
    """Build catalog entries (annotations broad → detailed, plus tags).

    Per object, the language annotations are the broad terms for its
    categories (see :data:`CATEGORY_ANNOTATIONS`) followed by the detailed
    product description; the tags are the normalized category labels plus
    ``box_gripper_graspable`` for ids in *graspable_ids* (defaults to the
    checked-in ``gso_graspable.json``).  Objects without Fuel metadata get
    an id-derived annotation and no category tags.
    """
    if graspable_ids is None:
        graspable_ids = _load_graspable_ids()
    missing = sorted(set(object_ids) - set(metadata))
    for object_id in missing:
        print(f"WARNING: no Fuel metadata for {object_id}; using id-derived annotation")

    catalog = {}
    for object_id in sorted(object_ids):
        meta = metadata.get(object_id, {})
        detailed = annotation_from_description(object_id, meta.get("description", ""))
        tags = sorted(tag_from_category(c) for c in meta.get("categories", []))
        if object_id in graspable_ids:
            tags = sorted(tags + [GRASPABLE_TAG])
        annotations = []
        for tag in tags:
            for term in CATEGORY_ANNOTATIONS.get(tag, ()):
                if term not in annotations:
                    annotations.append(term)
        if detailed not in annotations:
            annotations.append(detailed)
        catalog[object_id] = {"language_annotations": annotations, "tags": tags}
    return catalog


def write_catalog(
    out_root: Path, object_ids: list[str], metadata: dict,
    graspable_ids: set | None = None,
) -> None:
    catalog = build_catalog(object_ids, metadata, graspable_ids)
    (out_root / "catalog.json").write_text(
        json.dumps(catalog, indent=1, ensure_ascii=False) + "\n"
    )
    n_graspable = sum(1 for e in catalog.values() if GRASPABLE_TAG in e["tags"])
    print(f"Wrote {out_root / 'catalog.json'} with {len(catalog)} entries "
          f"({n_graspable} {GRASPABLE_TAG}).")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--source", type=Path, default=None,
        help="Existing clone of kevinzakka/mujoco_scanned_objects (may be a "
             "sparse checkout). If omitted, a shallow ~1 GB clone is made "
             "into a temp directory.",
    )
    parser.add_argument(
        "--output-dir", type=Path, required=True,
        help="Directory to place the prepared 'objects/gso' tree in.",
    )
    parser.add_argument(
        "--fuel-metadata", type=Path, default=_FUEL_METADATA_CACHE,
        help="JSON cache of Gazebo Fuel metadata ({id: {description, "
             "categories}}). Fetched from the Fuel API (and written to this "
             "path) when the file does not exist. Defaults to the checked-in "
             "cache under scripts/data/.",
    )
    args = parser.parse_args(argv)

    if args.source is not None:
        out_root, object_ids = prepare(
            args.source.expanduser().resolve(), args.output_dir,
        )
    else:
        with tempfile.TemporaryDirectory(prefix="gso_dataset_") as tmp:
            source = _clone_upstream(Path(tmp) / "mujoco_scanned_objects")
            out_root, object_ids = prepare(source, args.output_dir)

    if args.fuel_metadata.is_file():
        metadata = json.loads(args.fuel_metadata.read_text())
    else:
        print(f"Fetching Fuel metadata for {len(object_ids)} objects ...")
        metadata = fetch_fuel_metadata(object_ids)
        args.fuel_metadata.parent.mkdir(parents=True, exist_ok=True)
        args.fuel_metadata.write_text(
            json.dumps(metadata, indent=1, sort_keys=True, ensure_ascii=False)
        )
    write_catalog(out_root, object_ids, metadata)

    print(
        "\nTo upload (requires write access to the org):\n"
        f"  hf upload UniEnvOrg/unienv_genesis_collection_assets \\\n"
        f"      {out_root} objects/gso --repo-type dataset"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
