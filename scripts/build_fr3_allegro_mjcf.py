"""Build the FR3 + Wonik Allegro hand MJCFs (one per hand side) from the models in ``unienv_genesis_collection/assets``.

Writes ``franka_fr3_allegro/fr3_allegro_left.xml`` and ``fr3_allegro_right.xml``: the FR3 arm of
``franka_fr3_hand/fr3_hand.xml`` with its Franka Hand replaced by ``wonik_allegro/<side>_hand.xml``, mounted on the
flange through a 5 mm adapter plate and turned about the flange axis like the Franka Hand. Names are kept (``fr3_*``,
``palm``, ``ffj0`` ...); the Allegro's default classes and materials are prefixed ``allegro_`` because they collide
with the FR3's (``visual``, ``collision``, ``black``, ``white``). The robot class is
:class:`~unienv_genesis_collection.robots.franka_fr3_allegro.FrankaFR3WithAllegro`; a bimanual setup is two of them.

Run from the repository root:  python scripts/build_fr3_allegro_mjcf.py
"""

from __future__ import annotations

import copy
import pathlib
import xml.etree.ElementTree as ET

ROBOTS = pathlib.Path(__file__).resolve().parents[1] / "unienv_genesis_collection" / "assets" / "robots"

#: FR3 flange (end of link7) along link7 +z, and the hand's rotation about it (as for the Franka Hand: -45 deg).
FLANGE_Z = 0.107
FLANGE_QUAT = "0.9238795 0 0 -0.3826834"
#: Allegro palm origin above its mounting face (the palm's -z end, 0.095 m) plus a 5 mm adapter plate.
ALLEGRO_MOUNT_Z = 0.095 + 0.005
FR3_HOME = "0 0 0 -1.57079 0 1.57079 -0.7853"
#: Fingers straight, the thumb at its lowest (most opposed) base angle.
ALLEGRO_HOME = " ".join(["0"] * 12 + ["0.263", "0", "0", "0"])
PREFIX = "allegro_"


def _allegro(side: str):
    """``(default class, assets, palm body, actuators, contact exclusions)`` of the ``side`` Allegro hand."""
    src = ET.parse(ROBOTS / "wonik_allegro" / f"{side}_hand.xml").getroot()
    default = copy.deepcopy(src.find("default").find("default"))
    palm = copy.deepcopy(src.find("worldbody").find("body"))
    actuators = [copy.deepcopy(a) for a in src.find("actuator") if isinstance(a.tag, str)]
    excludes = [copy.deepcopy(e) for e in src.find("contact") if isinstance(e.tag, str)]
    for e in [*default.iter(), *palm.iter(), *(x for a in actuators for x in a.iter())]:
        for a in ("class", "childclass"):
            if a in e.attrib:
                e.set(a, PREFIX + e.get(a))
        if e.tag == "geom":
            for a in ("material", "mesh"):
                if a in e.attrib:
                    e.set(a, PREFIX + e.get(a))
    assets = []
    for m in src.find("asset"):
        if not isinstance(m.tag, str):
            continue
        c = copy.deepcopy(m)
        if c.tag == "material":
            c.set("name", PREFIX + c.get("name"))
        elif c.tag == "mesh":
            c.set("name", PREFIX + c.get("name", pathlib.Path(c.get("file")).stem))
            c.set("file", "../wonik_allegro/assets/" + c.get("file"))
        assets.append(c)
    palm.set("pos", f"0 0 {FLANGE_Z + ALLEGRO_MOUNT_Z:.4f}")
    palm.set("quat", FLANGE_QUAT)
    return default, assets, palm, actuators, excludes


def build(side: str) -> pathlib.Path:
    src = ET.parse(ROBOTS / "franka_fr3_hand" / "fr3_hand.xml").getroot()
    hand_default, hand_assets, palm, hand_actuators, hand_excludes = _allegro(side)
    root = ET.Element("mujoco", model=f"fr3_allegro_{side}")
    root.append(ET.Comment(" Generated by scripts/build_fr3_allegro_mjcf.py; do not edit by hand. "))
    ET.SubElement(root, "compiler", angle="radian", autolimits="true")
    ET.SubElement(root, "option", integrator="implicitfast")
    default = copy.deepcopy(src.find("default"))
    for d in list(default):  # keep the FR3 arm classes, drop the Franka Hand's
        if d.get("class") == "hand":
            default.remove(d)
    default.append(hand_default)
    root.append(default)
    asset = ET.SubElement(root, "asset")
    for m in src.find("asset"):
        if not isinstance(m.tag, str):
            continue
        if (m.tag == "mesh" and "franka_emika_panda" in m.get("file", "")) or m.get("name", "").startswith("hand_"):
            continue
        asset.append(copy.deepcopy(m))
    asset.extend(hand_assets)
    world = ET.SubElement(root, "worldbody")
    arm = copy.deepcopy(src.find("worldbody").find("body"))
    link7 = next(b for b in arm.iter("body") if b.get("name") == "fr3_link7")
    link7.remove(next(b for b in link7 if b.tag == "body" and b.get("name") == "hand"))
    link7.append(palm)
    world.append(arm)
    act = ET.SubElement(root, "actuator")
    act.extend(copy.deepcopy(a) for a in src.find("actuator") if isinstance(a.tag, str) and a.get("joint", "").startswith("fr3_"))
    act.extend(hand_actuators)
    con = ET.SubElement(root, "contact")
    ET.SubElement(con, "exclude", body1="fr3_link0", body2="fr3_link1")
    ET.SubElement(con, "exclude", body1="fr3_link7", body2="palm")
    con.extend(hand_excludes)
    ET.SubElement(ET.SubElement(root, "keyframe"), "key", name="home", qpos=f"{FR3_HOME} {ALLEGRO_HOME}")
    path = ROBOTS / "franka_fr3_allegro" / f"fr3_allegro_{side}.xml"
    path.parent.mkdir(parents=True, exist_ok=True)
    ET.indent(root, space="  ")
    ET.ElementTree(root).write(path, encoding="unicode")
    return path


if __name__ == "__main__":
    for s in ("left", "right"):
        print(build(s))
