"""Task props modelled in Blender: dustpan, hand brush, crumpled paper balls, shelf.

The props are generated by ``scripts/blender/make_props.py`` and hosted with the
other collection assets under ``objects/props/<name>/`` (downloaded on first
use, see :mod:`unienv_genesis_collection.asset_path`): a single-link URDF
tying textured / coloured visual meshes to convex collision pieces designed
alongside them, so physics never depends on mesh decomposition.

Every factory returns a :class:`UrdfPropObject`; :func:`surface_mesh` gives a
descriptor's local-frame visual surface (e.g. for sampling points on it).
Construction is offline-safe: the files are fetched when the prop's geometry
is first queried or the prop is loaded into a scene.
"""

from __future__ import annotations

import functools
import xml.etree.ElementTree as ET
from pathlib import Path
from typing import TYPE_CHECKING, List, Optional, Sequence, Tuple

from unienv_genesis_collection.objects.base_object import ManipulatableObject
from unienv_genesis_collection.objects.mesh_object import MeshObject

if TYPE_CHECKING:  # pragma: no cover
    import trimesh
    from unienv_genesis import GenesisWorld

__all__ = [
    "PROPS_ASSETS_ROOT",
    "PROP_NAMES",
    "UrdfPropObject",
    "surface_mesh",
    "dustpan",
    "hand_brush",
    "paper_ball",
    "shelf",
    "PAPER_BALL_VARIANTS",
    "DUSTPAN_MOUTH_HALF_WIDTH",
    "DUSTPAN_DEPTH",
    "DUSTPAN_HEIGHT",
    "SHELF_TOP_Z",
    "SHELF_TOP_HALF_EXTENTS",
]

#: Asset-collection directory of the props (``objects/props/<name>/<name>.urdf``).
PROPS_ASSETS_ROOT = "objects/props"

#: Crumpled paper variants (``paper_ball_<i>``).
PAPER_BALL_VARIANTS = 3

#: Every prop shipped under :data:`PROPS_ASSETS_ROOT`.
PROP_NAMES: Tuple[str, ...] = (
    "dustpan",
    "hand_brush",
    *(f"paper_ball_{i}" for i in range(PAPER_BALL_VARIANTS)),
    "shelf",
)

#: Dustpan geometry: mouth half width, pan depth and back-wall height (m).
DUSTPAN_MOUTH_HALF_WIDTH = 0.12
DUSTPAN_DEPTH = 0.20
DUSTPAN_HEIGHT = 0.075

#: Shelf geometry: top board surface height and the board's half extents (x, y), m.
SHELF_TOP_Z = 0.18
SHELF_TOP_HALF_EXTENTS = (0.116, 0.208)


class UrdfPropObject(MeshObject):
    """A single-link URDF prop under :data:`PROPS_ASSETS_ROOT`.

    A :class:`MeshObject` whose geometry (:meth:`_load_trimesh`, hence the
    local bounding box and the antipodal grasp candidates) is the union of
    its convex collision pieces — exactly what the physics sees;
    :meth:`visual_trimesh` is the rendered surface. Loaded as its URDF.

    Args:
        asset: Prop directory name (one of :data:`PROP_NAMES`).
        name: Entity name (default: ``asset``).
        fixed: Weld the prop to the world (e.g. a dustpan that only receives
            debris) instead of simulating it as a free body.
        language_annotations / standing_quaternion: As :class:`MeshObject`.
    """

    def __init__(
        self,
        asset: str,
        *,
        name: Optional[str] = None,
        fixed: bool = False,
        language_annotations: Optional[Sequence[str]] = None,
        standing_quaternion: Optional[Sequence[float]] = None,
    ) -> None:
        if asset not in PROP_NAMES:
            raise KeyError(f"unknown prop {asset!r}; expected one of {PROP_NAMES}")
        # ``mesh_file`` is resolved lazily (the collision pieces, see _load_trimesh).
        super().__init__(
            mesh_file=f"{PROPS_ASSETS_ROOT}/{asset}/{asset}.urdf",
            name=name or asset,
            fixed=fixed,
            language_annotations=language_annotations,
            standing_quaternion=standing_quaternion,
        )
        self.asset = asset

    @functools.cached_property
    def asset_dir(self) -> Path:
        """Local directory of the prop's files (downloaded on first access)."""
        from unienv_genesis_collection.asset_path import get_asset_path

        return get_asset_path(PROPS_ASSETS_ROOT, self.asset)

    @property
    def urdf_file(self) -> Path:
        return self.asset_dir / f"{self.asset}.urdf"

    def _mesh_files(self, kind: str) -> List[Path]:
        link = ET.parse(self.urdf_file).getroot().find("link")
        return [self.asset_dir / mesh.get("filename") for mesh in link.findall(f"{kind}/geometry/mesh")]

    @property
    def collision_files(self) -> List[Path]:
        return self._mesh_files("collision")

    @property
    def visual_files(self) -> List[Path]:
        return self._mesh_files("visual")

    def _load_trimesh(self) -> "trimesh.Trimesh":
        """Union of the convex collision pieces (cached)."""
        if self._trimesh_cache is None:
            import trimesh

            self._trimesh_cache = trimesh.util.concatenate(
                [trimesh.load(path, force="mesh") for path in self.collision_files]
            )
        return self._trimesh_cache

    @functools.cached_property
    def _visual_trimesh(self) -> "trimesh.Trimesh":
        import trimesh

        return trimesh.util.concatenate([trimesh.load(path, force="mesh") for path in self.visual_files])

    def visual_trimesh(self) -> "trimesh.Trimesh":
        """The rendered surface (all visual meshes)."""
        return self._visual_trimesh

    def load_into_scene(
        self,
        world: "GenesisWorld",
        pos: Tuple[float, float, float] = (0.0, 0.0, 0.0),
        quat: Tuple[float, float, float, float] = (1.0, 0.0, 0.0, 0.0),
        name_override: Optional[str] = None,
        batch_fixed_verts: bool = False,
    ):
        import genesis as gs

        morph = gs.morphs.URDF(
            file=str(self.urdf_file),
            pos=pos,
            quat=quat,
            fixed=self.fixed,
            batch_fixed_verts=batch_fixed_verts,
            # Nyx cannot export URDF entities whose fixed links were merged
            # (same as the YCB loader); single-link props lose nothing.
            merge_fixed_links=False,
        )
        return world.scene.add_entity(morph, name=name_override or self.name)


def surface_mesh(descriptor: ManipulatableObject) -> "trimesh.Trimesh":
    """Local-frame visual surface of *descriptor* (scaled), for point sampling."""
    loader = getattr(descriptor, "visual_trimesh", None) or getattr(descriptor, "_load_trimesh", None)
    if loader is None:
        raise TypeError(f"{type(descriptor).__name__} exposes no mesh to sample points from")
    return loader()


