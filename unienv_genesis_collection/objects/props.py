def dustpan(*, fixed: bool = False, name: Optional[str] = None) -> UrdfPropObject:
    """Blue plastic hand dustpan; mouth at local ``x = 0`` facing ``-x``, handle toward ``+x``.

    ``fixed=True`` welds it to the world (a pan that only receives debris);
    the default free body can be picked up by its handle.
    """
    return UrdfPropObject(
        "dustpan", name=name, fixed=fixed, language_annotations=("dustpan", "a blue plastic dustpan"),
    )


def hand_brush(*, name: Optional[str] = None) -> UrdfPropObject:
    """Wooden hand brush; long axis local ``x`` (handle at ``+x``), bristles down, sweeps along ``±y``."""
    return UrdfPropObject("hand_brush", name=name, language_annotations=("brush", "a wooden hand brush"))


def paper_ball(variant: int, *, name: Optional[str] = None) -> UrdfPropObject:
    """Crumpled paper ball ``variant`` (``0 .. PAPER_BALL_VARIANTS - 1``), origin at its bottom."""
    if not 0 <= int(variant) < PAPER_BALL_VARIANTS:
        raise ValueError(f"paper ball variant must be in [0, {PAPER_BALL_VARIANTS}), got {variant!r}")
    return UrdfPropObject(
        f"paper_ball_{int(variant)}", name=name, language_annotations=("paper", "a crumpled paper ball"),
    )


def shelf(*, fixed: bool = True, name: Optional[str] = None) -> UrdfPropObject:
    """Small open oak shelf, width along local ``y``; top board at :data:`SHELF_TOP_Z`."""
    return UrdfPropObject("shelf", name=name, fixed=fixed, language_annotations=("shelf", "a small wooden shelf"))
