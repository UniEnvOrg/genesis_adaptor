"""ReplicaCAD articulated furniture as :class:`ArticulatedObject` descriptors.

ReplicaCAD's articulated furniture (fridge, cabinets, drawers, …) is hosted
on the collection's Hugging Face assets repo under
``objects/replicacad/<item_id>/``.  Each item directory is self-contained::

    objects/replicacad/fridge/fridge.urdf   # authored URDF (convex collisions)
    objects/replicacad/fridge/*.glb         # GLB visual/collision meshes

Furniture is loaded via ``gs.morphs.URDF`` — the same loader YCB uses — with
``fixed=self.fixed`` (furniture is placed once at load), ``align=False``,
and **``merge_fixed_links=False``**: named door / drawer / handle links must
survive as entity links for the part-aware queries
(:meth:`~unienv_genesis_collection.objects.articulated_object.ArticulatedObject.list_part_grasping_candidates`,
:func:`~unienv_genesis_collection.objects.articulated_object.resolve_link_index`)
— same rationale as the ``YCBObject`` comment about link merging
(``merge_fixed_links=True`` is the URDF default and would weld them away).

Joint and link names are whatever the URDF declares; they are discovered at
runtime off the built entity — nothing per-asset is baked into code or the
catalog.  The catalog ships with the assets as
``objects/replicacad/catalog.json`` (language annotations + tags only —
tags gain values like ``"furniture"``, ``"articulated"``, ``"kitchen"``).

Typical usage::

    from unienv_genesis_collection.objects import (
        ReplicaCADFurniture, make_replicacad_pool,
    )

    fridge = ReplicaCADFurniture("fridge")
    pool = make_replicacad_pool(tags="articulated", n=4,
                                rng=torch.Generator().manual_seed(0))
"""

from __future__ import annotations

from typing import (
    Dict,
    FrozenSet,
    Iterable,
    List,
    Optional,
    Sequence,
    Tuple,
    Union,
    TYPE_CHECKING,
)

import torch

from unienv_genesis_collection.objects.articulated_object import (
    urdf_link_meshes_at_config,
)
from unienv_genesis_collection.objects.hub_objects.articulated.hub_articulated_object import (
    HubAssetArticulatedObject,
)
from unienv_genesis_collection.objects.hub_objects.catalog import (
    ObjectInfo,
    load_catalog,
)

if TYPE_CHECKING:
    from unienv_genesis.world.genesis_world import GenesisWorld

__all__ = [
    "REPLICACAD_ASSETS_ROOT",
    "REPLICACAD_CATALOG_PATH",
    "get_replicacad_catalog",
    "ReplicaCADFurniture",
    "list_replicacad_objects",
    "make_replicacad_pool",
]

# Path of the ReplicaCAD collection relative to the assets root (POSIX
# separators).
REPLICACAD_ASSETS_ROOT = "objects/replicacad"

# The catalog (language annotations + tags per item) ships with the assets as
# ``objects/replicacad/catalog.json``; it is generated by
# ``scripts/prepare_replicacad_assets.py`` from the furniture URDF subset.
REPLICACAD_CATALOG_PATH = f"{REPLICACAD_ASSETS_ROOT}/catalog.json"


def get_replicacad_catalog() -> Dict[str, ObjectInfo]:
    """Return the ReplicaCAD catalog (item id → :class:`ObjectInfo`).

    Loaded from ``objects/replicacad/catalog.json`` in the assets folder
    (downloaded on first use) and cached.
    """
    return load_catalog(REPLICACAD_CATALOG_PATH)


def list_replicacad_objects(
    *,
    tags: Optional[Union[str, Iterable[str]]] = None,
) -> List[str]:
    """Return ReplicaCAD item ids, optionally filtered by tags.

    Works fully offline — only the generated catalog is consulted.

    Args:
        tags: A tag or iterable of tags.  Only items carrying **all** of them
            are returned.  ``None`` returns every item.

    Returns:
        Sorted list of item ids.
    """
    if tags is None:
        wanted: FrozenSet[str] = frozenset()
    elif isinstance(tags, str):
        wanted = frozenset((tags,))
    else:
        wanted = frozenset(tags)
    return sorted(
        object_id
        for object_id, info in get_replicacad_catalog().items()
        if wanted <= info.tags
    )


# ---------------------------------------------------------------------------
# ReplicaCADFurniture
# ---------------------------------------------------------------------------

class ReplicaCADFurniture(HubAssetArticulatedObject):
    """ReplicaCAD articulated furniture loaded into Genesis via its URDF.

    Loads with ``fixed=self.fixed``, ``align=False`` and
    ``merge_fixed_links=False`` — named door / drawer / handle links must
    survive merging so they stay addressable by name for part queries (same
    rationale as the ``YCBObject`` link-merging comment; URDF morphs merge
    fixed links by default, which would weld them away).

    Construction is offline-safe; assets are downloaded lazily on first
    scene load or geometry query and verified for completeness (the URDF
    references its meshes, which must all be present locally).

    Args:
        object_id: Catalog id, e.g. ``"fridge"``.  See
            :func:`get_replicacad_catalog` or :func:`list_replicacad_objects`.
        scale: Uniform scalar or per-axis ``(sx, sy, sz)`` scale factor.
        name: Technical identifier; defaults to *object_id*.
        fixed: Whether the furniture is immovable (furniture is placed once
            at load; the morph flag carries it — URDF, unlike MJCF, has a
            ``fixed=`` option).
        reference_qpos: Joint name → position at the reference configuration
            used by the offline union bbox (default all-zero = the authored
            closed pose).
        language_annotations: Override the catalog's default annotations.
        standing_quaternion: Optional ``(w, x, y, z)`` orientation used by
            :meth:`set_pos_3d` instead of the identity when the furniture is
            placed without randomisation.  Defaults to the catalog's
            ``standing_quaternion`` metadata when present.
    """

    def __init__(
        self,
        object_id: str,
        scale: Union[float, Tuple[float, float, float]] = 1.0,
        name: Optional[str] = None,
        fixed: bool = True,
        reference_qpos: Optional[Dict[str, float]] = None,
        language_annotations: Optional[Sequence[str]] = None,
        standing_quaternion: Optional[Sequence[float]] = None,
    ):
        catalog = get_replicacad_catalog()
        info = catalog.get(object_id)
        if info is None:
            raise KeyError(
                f"Unknown ReplicaCAD item id: {object_id!r}. "
                f"See list_replicacad_objects() for the {len(catalog)} available ids."
            )
        super().__init__(
            asset_relative_dir=f"{REPLICACAD_ASSETS_ROOT}/{object_id}",
            description_file_name=f"{object_id}.urdf",
            name=name or object_id,
            fixed=fixed,
            reference_qpos=reference_qpos,
            language_annotations=(
                language_annotations
                if language_annotations is not None
                else info.language_annotations
            ),
            scale=scale,
            standing_quaternion=(
                standing_quaternion
                if standing_quaternion is not None
                else info.standing_quaternion
            ),
        )
        self.object_id = object_id
        self.info = info
        # Scalar scales are passed to the morph as float, per-axis as tuple.
        self._morph_scale: Union[float, Tuple[float, float, float]] = (
            scale if isinstance(scale, tuple) else float(scale)
        )

    def _load_link_meshes_at_reference(self):
        """Per-link visual meshes at the reference configuration (offline FK).

        Uses :func:`~unienv_genesis_collection.objects.articulated_object.urdf_link_meshes_at_config`
        (``genesis.ext.urdfpy`` forward kinematics — no Genesis scene); the
        result feeds the union :meth:`get_local_bounding_box`.  Assets are
        ensured first so the meshes exist locally.
        """
        self._ensure_assets()
        return urdf_link_meshes_at_config(self.description_file, self.reference_qpos)

    def _load_link_local_meshes_at_reference(self):
        """Per-link visual meshes in the link's own frame (offline FK).

        Part-grasp enumeration frame for
        :meth:`~unienv_genesis_collection.objects.articulated_object.ArticulatedObject.list_part_grasping_candidates`:
        the URDF visuals with ``<visual><origin>`` applied only (no
        ``base_T_link`` FK transform — configuration-independent), via
        :func:`~unienv_genesis_collection.objects.articulated_object.urdf_link_meshes_at_config`
        with ``link_local=True``.  Assets are ensured first so the meshes
        exist locally.
        """
        self._ensure_assets()
        return urdf_link_meshes_at_config(
            self.description_file, self.reference_qpos, link_local=True,
        )

    def load_into_scene(
        self,
        world: "GenesisWorld",
        pos=(0.0, 0.0, 0.0),
        quat=(1.0, 0.0, 0.0, 0.0),
        name_override=None,
        batch_fixed_verts=False,
    ):
        """Load the furniture URDF into the scene (``gs.morphs.URDF``).

        Identical morph options to ``YCBObject.load_into_scene``, with
        ``fixed=self.fixed``.  ``merge_fixed_links=False`` keeps the original
        link structure so named door/drawer links survive for part queries.

        Args:
            world: ``GenesisWorld`` with an unbuilt scene.
            pos: World position ``(x, y, z)``.
            quat: World orientation ``(w, x, y, z)``.
            name_override: Override the default ``self.name``.
            batch_fixed_verts: Enable per-env position overrides for fixed
                entities in batched worlds (significant memory cost).

        Returns:
            A Genesis entity reference.
        """
        import genesis as gs

        self._ensure_assets()
        morph = gs.morphs.URDF(
            file=str(self.description_file),
            scale=self._morph_scale,
            pos=pos,
            quat=quat,
            align=False,
            fixed=self.fixed,
            batch_fixed_verts=batch_fixed_verts,
            # Nyx currently cannot export URDF entities after Genesis merges
            # fixed links; keeping them also preserves the named door /
            # drawer links the part-aware queries address by name.
            merge_fixed_links=False,
        )
        # No surface override: Default() preserves the texture from the asset.
        return world.scene.add_entity(
            morph,
            name=name_override or self.name,
        )


# ---------------------------------------------------------------------------
# Pool building
# ---------------------------------------------------------------------------

def make_replicacad_pool(
    object_ids: Optional[Sequence[str]] = None,
    *,
    tags: Optional[Union[str, Iterable[str]]] = None,
    n: Optional[int] = None,
    rng: Optional[torch.Generator] = None,
    **object_kwargs,
) -> List[ReplicaCADFurniture]:
    """Build a list of :class:`ReplicaCADFurniture` for use as a furniture pool.

    The result plugs directly into consumers such as the room builder's
    ``furniture_pool``.  Construction does not download anything; assets are
    fetched when the items are first loaded into a scene.

    Args:
        object_ids: Explicit ids to use (order preserved).  Mutually
            exclusive with *tags*.
        tags: Filter the catalog by category tags (see
            :func:`list_replicacad_objects`).
        n: If given, sample *n* distinct items from the selection.
        rng: Optional :class:`torch.Generator` for reproducible sampling.
            When omitted (``None``), the global Torch RNG is used.
        **object_kwargs: Forwarded to every :class:`ReplicaCADFurniture`
            (e.g. ``scale=0.8``).

    Returns:
        List of :class:`ReplicaCADFurniture` descriptors with unique names.

    Raises:
        ValueError: If both *object_ids* and *tags* are given, or *n*
            exceeds the number of selected items.
        KeyError: If an explicit id is not in the catalog.
    """
    if object_ids is not None and tags is not None:
        raise ValueError("Pass either object_ids or tags, not both.")

    ids = (
        list(object_ids) if object_ids is not None else list_replicacad_objects(tags=tags)
    )

    if n is not None:
        if n > len(ids):
            raise ValueError(
                f"Requested {n} items but only {len(ids)} match the selection."
            )
        # Pin the output device to the generator's device: with a Genesis
        # CUDA default device, an unpinned randperm would create a CUDA tensor
        # from a CPU generator and raise a device-mismatch error.
        perm = torch.randperm(
            len(ids), generator=rng, device=rng.device if rng is not None else None
        )[:n].tolist()
        ids = [ids[i] for i in perm]

    return [ReplicaCADFurniture(object_id, **object_kwargs) for object_id in ids]
