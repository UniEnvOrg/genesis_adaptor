"""Lightwheel SimReady (open bundle) USD articulated furniture as :class:`ArticulatedObject` descriptors.

The Lightwheel AI open-source bundle (`LightwheelAI/Lightwheel-simready-asset
<https://github.com/LightwheelAI/Lightwheel-simready-asset>`_) ships
**259 SimReady USD assets** (one USD per object + a ``texture/`` sidecar
directory).  The collection hosts a repackaged subset of the
``Manipulation/`` assets on its Hugging Face assets repo under
``objects/lightwheel/<object_id>/``, one self-contained directory per
object::

    objects/lightwheel/lightwheel_Microwave043/lightwheel_Microwave043.usd
    objects/lightwheel/lightwheel_Microwave043/texture/*.png

**Materials — mandatory adaptation.**  The bundle authors shading as
**OmniPBR MDL** (``info:implementationSource = 'sourceAsset'``, ``info:mdl:sourceAsset
= @OmniPBR.mdl@``), which usd-core cannot read — Genesis loses the materials
silently (default grey).  The packaging step rewrites every OmniPBR graph
into native ``UsdPreviewSurface`` + ``UsdUVTexture`` with
:func:`~unienv_genesis_collection.utils.usd_conversions.convert_mdl_to_preview_surface`,
recovering full PBR with the articulation untouched (verified: 4/4 materials
of Microwave043 parse as color/roughness/metallic image textures after the
rewrite).

**Articulation is native UsdPhysics and already Genesis-ordered** — the
bundle authors ``body0`` = parent / ``body1`` = child (the *opposite* of
MolmoSpaces), so no joint-body swap is needed; ``add_stage`` splits each
per-object stage into exactly **one** entity (verified: Microwave043 →
3 links / 2 revolute DOFs, Stovetop002 → 5 links / 4 revolute, Toaster003 →
5 links / 1 revolute + 2 prismatic).

Furniture is loaded via ``gs.morphs.USD`` + ``scene.add_stage``; Genesis's
full-path USD joint/link names are sanitised to *clean leaf names* exactly
like the ArtVIP family.  Some assets weld their base to the world upstream
(``physics:kinematicEnabled`` on the base body — Stovetop002); the
descriptor's ``fixed`` morph flag overrides root fixity at load like the
other USD siblings.

**License — CC BY-NC 4.0 (non-commercial).**  The bundle's ``LICENSE`` and
README state "Creative Commons Attribution-NonCommercial 4.0 International"
("Free for non-commercial use") and require the ``lightwheel_{asset_name}``
naming format for attribution — hence the ``lightwheel_``-prefixed object
ids.  Attribution and the license ship verbatim next to the assets; the
non-commercial clause is accepted by the collection maintainer and flagged
in ``docs/articulated_rooms.md`` (mirroring the ReplicaCAD caveat).

The catalog ships with the assets as ``objects/lightwheel/catalog.json``.

Typical usage::

    from unienv_genesis_collection.objects import (
        LightwheelFurniture, make_lightwheel_pool,
    )

    microwave = LightwheelFurniture("lightwheel_Microwave043")
    pool = make_lightwheel_pool(tags="kitchen", n=4,
                                rng=torch.Generator().manual_seed(0))
"""

