def make_robocasa_pool(
    object_ids: Optional[Sequence[str]] = None,
    *,
    tags: Optional[Union[str, Iterable[str]]] = None,
    contains: Optional[str] = None,
    n: Optional[int] = None,
    rng: Optional[torch.Generator] = None,
    **object_kwargs,
) -> List[RoboCasaFixture]:
    """Build a list of :class:`RoboCasaFixture` for use as a furniture pool.

    The result plugs directly into consumers such as the room builder's
    ``furniture_pool``.  Construction does not download anything; assets are
    fetched when the fixtures are first loaded into a scene.

    Args:
        object_ids: Explicit ids to use (order preserved).  Mutually
            exclusive with *tags* / *contains*.
        tags: Filter the catalog by category tags (see
            :func:`list_robocasa_objects`).
        contains: Filter ids by case-insensitive substring (see
            :func:`list_robocasa_objects`).  Combinable with *tags*.
        n: If given, sample *n* distinct fixtures from the selection.
        rng: Optional :class:`torch.Generator` for reproducible sampling.
            When omitted (``None``), the global Torch RNG is used.
        **object_kwargs: Forwarded to every :class:`RoboCasaFixture` (e.g.
            ``scale=0.8``).

    Returns:
        List of :class:`RoboCasaFixture` descriptors with unique names.

    Raises:
        ValueError: If *object_ids* is combined with *tags* / *contains*,
            or *n* exceeds the number of selected fixtures.
        KeyError: If an explicit id is not in the catalog.
    """
    if object_ids is not None and (tags is not None or contains is not None):
        raise ValueError("Pass either object_ids or tags/contains, not both.")

    ids = (
        list(object_ids)
        if object_ids is not None
        else list_robocasa_objects(tags=tags, contains=contains)
    )

    if n is not None:
        if n > len(ids):
            raise ValueError(
                f"Requested {n} fixtures but only {len(ids)} match the selection."
            )
        # Pin the output device to the generator's device: with a Genesis
        # CUDA default device, an unpinned randperm would create a CUDA tensor
        # from a CPU generator and raise a device-mismatch error.
        perm = torch.randperm(
            len(ids), generator=rng, device=rng.device if rng is not None else None
        )[:n].tolist()
        ids = [ids[i] for i in perm]

    return [RoboCasaFixture(object_id, **object_kwargs) for object_id in ids]
