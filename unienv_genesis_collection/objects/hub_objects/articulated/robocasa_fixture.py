"""RoboCasa kitchen fixtures as :class:`ArticulatedObject` descriptors.

RoboCasa kitchen fixtures (cabinets, drawers, appliances, counters) are
articulated MJCF models hosted on the collection's Hugging Face assets repo
under ``objects/robocasa/<fixture_id>/``.  Each fixture directory is
self-contained::

    objects/robocasa/cabinet_hinge/model.xml        # jointless root = welded
    objects/robocasa/cabinet_hinge/shared_assets.xml  # <include> registries
    objects/robocasa/cabinet_hinge/meshes/*.obj       # + textures

Fixtures are loaded via ``gs.morphs.MJCF`` — the same loader GSO uses.  **MJCF
has no ``fixed=`` morph flag**: the XML decides.  A jointless root body is
welded to the world (the fixed-GSO ``model.xml`` trick), so a fixed fixture is
an MJCF *without* ``<freejoint/>``; a movable variant would inject one,
mirroring ``scripts/prepare_gso_assets.py``.  The descriptor therefore does
not pass a fixed flag to the morph and instead checks at load time that the
XML agrees with :attr:`fixed` (warning otherwise, mirroring
``unienv_genesis/nodes/entities/robot_node.py``).

Joint and link names are whatever the MJCF declares; they are discovered at
runtime off the built entity
(:func:`~unienv_genesis_collection.objects.articulated_object.resolve_joint_dofs`
/ :func:`~unienv_genesis_collection.objects.articulated_object.resolve_link_index`)
— nothing per-asset is baked into code or the catalog.  The catalog ships
with the assets as ``objects/robocasa/catalog.json`` (language annotations +
tags only — tags gain values like ``"furniture"``, ``"articulated"``,
``"kitchen"`` for pool filtering).

Typical usage::

    from unienv_genesis_collection.objects import RoboCasaFixture, make_robocasa_pool

    cabinet = RoboCasaFixture("cabinet_hinge")
    pool = make_robocasa_pool(tags="kitchen", n=4,
                              rng=torch.Generator().manual_seed(0))
"""

from __future__ import annotations

import logging
from typing import (
    Dict,
    FrozenSet,
    Iterable,
    List,
    Optional,
    Sequence,
    Union,
    TYPE_CHECKING,
)

import torch

from unienv_genesis_collection.objects.articulated_object import (
    mjcf_link_meshes_at_config,
)
from unienv_genesis_collection.objects.hub_objects.articulated.hub_articulated_object import (
    HubAssetArticulatedObject,
)
from unienv_genesis_collection.objects.hub_objects.catalog import (
    ObjectInfo,
    load_catalog,
)

if TYPE_CHECKING:
    from unienv_genesis.world.genesis_world import GenesisWorld

__all__ = [
    "ROBOCASA_ASSETS_ROOT",
    "ROBOCASA_CATALOG_PATH",
    "get_robocasa_catalog",
    "RoboCasaFixture",
    "list_robocasa_objects",
    "make_robocasa_pool",
]

logger = logging.getLogger(__name__)

# Path of the RoboCasa collection relative to the assets root (POSIX separators).
ROBOCASA_ASSETS_ROOT = "objects/robocasa"

# The catalog (language annotations + tags per fixture) ships with the assets
# as ``objects/robocasa/catalog.json``; it is generated by
# ``scripts/prepare_robocasa_assets.py`` from the fixture registry subset.
ROBOCASA_CATALOG_PATH = f"{ROBOCASA_ASSETS_ROOT}/catalog.json"


def get_robocasa_catalog() -> Dict[str, ObjectInfo]:
    """Return the RoboCasa catalog (fixture id → :class:`ObjectInfo`).

    Loaded from ``objects/robocasa/catalog.json`` in the assets folder
    (downloaded on first use) and cached.
    """
    return load_catalog(ROBOCASA_CATALOG_PATH)


def list_robocasa_objects(
    *,
    tags: Optional[Union[str, Iterable[str]]] = None,
    contains: Optional[str] = None,
) -> List[str]:
    """Return RoboCasa fixture ids, optionally filtered by tags and/or substring.

    Works fully offline — only the generated catalog is consulted.

    Args:
        tags: A tag or iterable of tags.  Only fixtures carrying **all** of
            them are returned (e.g. ``"kitchen"``, ``"articulated"``).
        contains: Case-insensitive substring to filter ids by (e.g.
            ``"cabinet"``).  Combinable with *tags*.

    Returns:
        Sorted list of fixture ids.
    """
    if tags is None:
        wanted: FrozenSet[str] = frozenset()
    elif isinstance(tags, str):
        wanted = frozenset((tags,))
    else:
        wanted = frozenset(tags)
    needle = contains.lower() if contains is not None else None
    return sorted(
        object_id
        for object_id, info in get_robocasa_catalog().items()
        if wanted <= info.tags
        and (needle is None or needle in object_id.lower())
    )


