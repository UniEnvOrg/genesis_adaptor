# RoboCasaFixture
# ---------------------------------------------------------------------------

class RoboCasaFixture(HubAssetArticulatedObject):
    """A RoboCasa kitchen fixture loaded into Genesis via its MJCF model.

    The jointless root of the fixture MJCF makes the base welded to the world
    (fixed furniture, exactly the ``GSOObject`` fixed path); joint/link names
    are discovered at runtime off the built entity — never baked.

    Construction is offline-safe; assets are downloaded lazily on first
    scene load or geometry query and verified for completeness (the MJCF and
    its ``<include>`` chain reference meshes/textures which must all be
    present locally).

    Args:
        object_id: Fixture id, e.g. ``"cabinet_hinge"``.  See
            :func:`get_robocasa_catalog` or :func:`list_robocasa_objects`.
        scale: Uniform scale factor.  MJCF morphs do not support per-axis
            scaling.
        name: Technical identifier; defaults to *object_id*.
        fixed: Whether the fixture is immovable.  Note that MJCF morphs have
            no ``fixed=`` flag — the asset's jointless root decides (see the
            module docstring).  ``fixed=True`` (the default) additionally
            warns at load time when the MJCF declares a ``freejoint``.
        reference_qpos: Joint name → position at the reference configuration
            used by the offline union bbox (default all-zero = the authored
            closed pose).
        language_annotations: Override the catalog's default annotation.
        standing_quaternion: Optional ``(w, x, y, z)`` orientation used by
            :meth:`set_pos_3d` instead of the identity when the fixture is
            placed without randomisation.  Defaults to the catalog's
            ``standing_quaternion`` metadata when present.
    """

    def __init__(
        self,
        object_id: str,
        scale: float = 1.0,
        name: Optional[str] = None,
        fixed: bool = True,
        reference_qpos: Optional[Dict[str, float]] = None,
        language_annotations: Optional[Sequence[str]] = None,
        standing_quaternion: Optional[Sequence[float]] = None,
    ):
        catalog = get_robocasa_catalog()
        info = catalog.get(object_id)
        if info is None:
            raise KeyError(
                f"Unknown RoboCasa fixture id: {object_id!r}. "
                f"See list_robocasa_objects() for the {len(catalog)} available ids."
            )
        if isinstance(scale, tuple):
            raise ValueError(
                "RoboCasaFixture only supports uniform (scalar) scaling: "
                "anisotropic scaling is not supported by MJCF morphs."
            )
        super().__init__(
            asset_relative_dir=f"{ROBOCASA_ASSETS_ROOT}/{object_id}",
            description_file_name="model.xml",
            name=name or object_id,
            fixed=fixed,
            reference_qpos=reference_qpos,
            language_annotations=(
                language_annotations
                if language_annotations is not None
                else info.language_annotations
            ),
            scale=scale,
            standing_quaternion=(
                standing_quaternion
                if standing_quaternion is not None
                else info.standing_quaternion
            ),
        )
        self.object_id = object_id
        self.info = info
        self._morph_scale = float(scale)

    def _warn_on_freejoint_mismatch(self) -> None:
        """Warn when the fixture MJCF disagrees with :attr:`fixed`.

        MJCF morphs have no ``fixed=`` flag — Genesis always follows the MJCF
        specification, so a jointless root is welded (fixed) and a
        ``<freejoint/>`` root is movable regardless of :attr:`fixed`.  Mirrors
        the load-time check in
        ``unienv_genesis/nodes/entities/robot_node.py`` (``initialize_entity_from_description_file``).
        """
        try:
            content = self.description_file.read_text()
        except OSError:
            return  # the loader will report the missing / unreadable file
        has_freejoint = content.find("freejoint") != -1
        if has_freejoint and self.fixed:
            logger.warning(
                "Fixture %r is loaded with fixed=True, but the MJCF %s has "
                "`freejoint` attributes. By default Genesis will always follow "
                "the MJCF specification, so the fixture will be movable — which "
                "may cause unexpected behaviors.",
                self.name,
                self.description_file,
            )
        elif not has_freejoint and not self.fixed:
            logger.warning(
                "Fixture %r is loaded with fixed=False, but the MJCF %s does "
                "not have `freejoint` attributes. By default Genesis will "
                "always follow the MJCF specification, so the fixture will be "
                "welded to the world — which may cause unexpected behaviors.",
                self.name,
                self.description_file,
            )

    def _load_link_meshes_at_reference(self):
        """Per-body visual meshes at the reference configuration (offline FK).

        Uses :func:`~unienv_genesis_collection.objects.articulated_object.mjcf_link_meshes_at_config`
        (Genesis has no MJCF FK API); the result feeds the union
        :meth:`get_local_bounding_box`.  Assets are ensured first so the
        meshes exist locally.
        """
        self._ensure_assets()
        return mjcf_link_meshes_at_config(self.description_file, self.reference_qpos)

    def _load_link_local_meshes_at_reference(self):
        """Per-body visual meshes in the body's own frame (offline FK).

        Part-grasp enumeration frame for
        :meth:`~unienv_genesis_collection.objects.articulated_object.ArticulatedObject.list_part_grasping_candidates`:
        each mesh geom with its own ``pos``/``quat``/``euler`` applied only
        (no accumulated parent/body/joint chain — configuration-independent),
        via :func:`~unienv_genesis_collection.objects.articulated_object.mjcf_link_meshes_at_config`
        with ``link_local=True``.  Assets are ensured first so the meshes
        exist locally.
        """
        self._ensure_assets()
        return mjcf_link_meshes_at_config(
            self.description_file, self.reference_qpos, link_local=True,
        )

    def load_into_scene(
        self,
        world: "GenesisWorld",
        pos=(0.0, 0.0, 0.0),
        quat=(1.0, 0.0, 0.0, 0.0),
        name_override=None,
        batch_fixed_verts=False,
    ):
        """Load the fixture MJCF into the scene (``gs.morphs.MJCF``).

        Identical morph options to ``GSOObject.load_into_scene`` — there is
        deliberately **no ``fixed=`` kwarg** (MJCF morphs don't have one; the
        asset's jointless root makes the fixture fixed), so placement is
        carried by the morph ``pos`` / ``quat``.

        Args:
            world: ``GenesisWorld`` with an unbuilt scene.
            pos: World position ``(x, y, z)``.
            quat: World orientation ``(w, x, y, z)``.
            name_override: Override the default ``self.name``.
            batch_fixed_verts: Enable per-env position overrides for fixed
                entities in batched worlds (significant memory cost).

        Returns:
            A Genesis entity reference.
        """
        import genesis as gs

        self._ensure_assets()
        self._warn_on_freejoint_mismatch()
        morph = gs.morphs.MJCF(
            file=str(self.description_file),
            scale=self._morph_scale,
            pos=pos,
            quat=quat,
            align=False,
            batch_fixed_verts=batch_fixed_verts,
            requires_jac_and_IK=False,
        )
        # No surface override: Default() preserves the MJCF-bound material.
        return world.scene.add_entity(
            morph,
            name=name_override or self.name,
        )


