"""MolmoSpaces (Ai2-THOR) USD articulated furniture as :class:`ArticulatedObject` descriptors.

The MolmoSpaces dataset (`allenai/molmospaces
<https://huggingface.co/datasets/allenai/molmospaces>`_) ships **Isaac-ready
USD objects** converted from the Ai2-THOR asset library.  The collection
hosts a repackaged subset of the ``isaac/objects/thor`` subtree (CC BY 4.0)
on its Hugging Face assets repo under ``objects/molmospaces/<object_id>/``,
one self-contained directory per object::

    objects/molmospaces/fridge_26/fridge_26.usda
    objects/molmospaces/fridge_26/Textures/*.png            # relative textures

Every object is the upstream **``<Name>_mesh`` variant**: it replaces the
base variant's cube ``…_PrimitiveCollider`` prims with convex-hull
``Mesh`` colliders (``physics:approximation = "convexHull"``, e.g. 14
colliders for Fridge_26 instead of 281) — the closest collider proxy at the
lowest collider count; the alternative ``_prim``/base variants stay upstream.

Materials are **100 % UsdPreviewSurface** (no MDL anywhere in the thor USD
subset), textures are separate ``Textures/*.png`` files referenced
relatively — Genesis-native without conversion.

**Joint-body swap (mandatory adaptation).**  MolmoSpaces authors joints with
``body0`` = child and ``body1`` = parent (the MJCF/PhysX order), which is the
reverse of Genesis's loader contract: as shipped, 12/18 probed samples *fail
to load* (``Link … has multiple parents``) and the remaining 6 load with the
movable part in the base link.  The packaging step rewrites every joint with
:func:`~unienv_genesis_collection.utils.usd_conversions.swap_usd_joint_bodies`
(relationship targets **and** the per-side ``localPos/localRot`` frames), so
the packaged stages load 18/18 single-entity with the correct base link —
per-object details in ``packaging_log.json``.

Furniture is loaded via ``gs.morphs.USD`` + ``scene.add_stage`` (single
entity asserted), and Genesis's full-path USD joint/link names are
sanitised to *clean leaf names* exactly like the ArtVIP family — see the
ArtVIP module docstring for the shared name-translation contract.

The catalog ships with the assets as ``objects/molmospaces/catalog.json``
(``Catalog``-schema: language annotations + tags).

Typical usage::

    from unienv_genesis_collection.objects import (
        MolmoSpacesFurniture, make_molmospaces_pool,
    )

    fridge = MolmoSpacesFurniture("fridge_26")
    pool = make_molmospaces_pool(tags="kitchen", n=4,
                                 rng=torch.Generator().manual_seed(0))
"""

