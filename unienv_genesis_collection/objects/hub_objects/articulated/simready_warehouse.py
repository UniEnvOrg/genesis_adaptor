# Path of the SimReady Warehouse collection relative to the assets root.
SIMREADY_WAREHOUSE_ASSETS_ROOT = "objects/simready_warehouse"

# The catalog (language annotations + tags per object) ships with the assets
# as ``objects/simready_warehouse/catalog.json``; it is generated by
# ``scripts/prepare_simready_warehouse_assets.py`` from the dataset CSV.
SIMREADY_WAREHOUSE_CATALOG_PATH = f"{SIMREADY_WAREHOUSE_ASSETS_ROOT}/catalog.json"


def get_simready_warehouse_catalog() -> Dict[str, ObjectInfo]:
    """Return the SimReady Warehouse catalog (object id → :class:`ObjectInfo`).

    Loaded from ``objects/simready_warehouse/catalog.json`` in the assets
    folder (downloaded on first use) and cached.
    """
    return load_catalog(SIMREADY_WAREHOUSE_CATALOG_PATH)


def list_simready_warehouse_objects(
    *,
    tags: Optional[Union[str, Iterable[str]]] = None,
    contains: Optional[str] = None,
) -> List[str]:
    """Return SimReady Warehouse prop ids, optionally filtered by tags/substring.

    Works fully offline — only the generated catalog is consulted.

    Args:
        tags: A tag or iterable of tags.  Only props carrying **all** of
            them are returned (e.g. ``"prop"``, ``"rigid"``).
        contains: Case-insensitive substring to filter ids by (e.g.
            ``"cardbox"``).  Combinable with *tags*.

    Returns:
        Sorted list of object ids.
    """
    if tags is None:
        wanted: FrozenSet[str] = frozenset()
    elif isinstance(tags, str):
        wanted = frozenset((tags,))
    else:
        wanted = frozenset(tags)
    needle = contains.lower() if contains is not None else None
    return sorted(
        object_id
        for object_id, info in get_simready_warehouse_catalog().items()
        if wanted <= info.tags
        and (needle is None or needle in object_id.lower())
    )


# ---------------------------------------------------------------------------
# SimReadyWarehouseProp
# ---------------------------------------------------------------------------

class SimReadyWarehouseProp(HubAssetArticulatedObject):
    """A SimReady Warehouse rigid prop loaded via ``scene.add_stage``.

    Rigid static prop (zero articulation upstream — the packaged stages
    carry the ``RigidBodyAPI`` authoring), so the descriptor is a member of
    the articulated furniture family with an **empty joint set**:

    * ``load_into_scene`` splits into exactly **one** welded entity
      (asserted; ``fixed=False`` loads it as a free rigid body instead);
    * ``list_joint_names()`` → ``[]``; joint DoF queries raise the usual
      resolution errors (there is nothing to drive);
    * ``list_link_names()`` → the single root body's clean name;
      ``get_local_bounding_box()`` is the whole-prop box via the offline FK
      walker (which degenerates to the authored stage frame for a jointless
      root);
    * ``name_override`` is warned-and-ignored like the other USD siblings.

    Construction is offline-safe; assets are downloaded lazily on first
    scene load or geometry query and verified for completeness (the packaged
    stage + every ``materials/textures`` file it references must be present
    locally).

    Args:
        object_id: Catalog id, e.g. ``"prop_cardbox_c1"``.  See
            :func:`get_simready_warehouse_catalog` or
            :func:`list_simready_warehouse_objects`.
        scale: Uniform scale factor (scalar only, like the USD/ArtVIP family).
        name: Technical identifier; defaults to *object_id*.
        fixed: Whether the prop is immovable (``True`` — the default — welds
            the packaged ``RigidBodyAPI`` root; ``False`` leaves it dynamic).
        reference_qpos: Unused for rigid props (no joints); accepted for the
            shared descriptor contract and ignored.
        language_annotations: Override the catalog's default annotations.
        standing_quaternion: Optional ``(w, x, y, z)`` orientation used by
            ``set_pos_3d``/room placements instead of the identity.
        description_file_name: Override the packaged description file name
            (default ``"<object_id>.usd"`` — the physics overlay variant).
    """

    def __init__(
        self,
        object_id: str,
        scale: float = 1.0,
        name: Optional[str] = None,
        fixed: bool = True,
        reference_qpos: Optional[Dict[str, float]] = None,
        language_annotations: Optional[Sequence[str]] = None,
        standing_quaternion: Optional[Sequence[float]] = None,
        description_file_name: Optional[str] = None,
    ):
        catalog = get_simready_warehouse_catalog()
        info = catalog.get(object_id)
        if info is None:
            raise KeyError(
                f"Unknown SimReady Warehouse prop id: {object_id!r}. "
                f"See list_simready_warehouse_objects() for the {len(catalog)} "
                "available ids."
            )
        if isinstance(scale, tuple):
            raise ValueError(
                "SimReadyWarehouseProp only supports uniform (scalar) scaling: "
                "per-axis scale is a gs.morphs.Mesh-only feature."
            )
        if reference_qpos:
            raise ValueError(
                "SimReadyWarehouseProp is a rigid prop (no joints): "
                "reference_qpos must be empty or None."
            )
        super().__init__(
            asset_relative_dir=f"{SIMREADY_WAREHOUSE_ASSETS_ROOT}/{object_id}",
            description_file_name=description_file_name or f"{object_id}.usd",
            name=name or object_id,
            fixed=fixed,
            reference_qpos=None,
            language_annotations=(
                language_annotations
                if language_annotations is not None
                else info.language_annotations
            ),
            scale=scale,
            standing_quaternion=(
                standing_quaternion
                if standing_quaternion is not None
                else info.standing_quaternion
            ),
        )
        self.object_id = object_id
        self.info = info
        self._morph_scale = float(scale)
        # Lazy (offline pxr) clean-name translation layer, built on first use.
        self._name_maps: Optional[
            Tuple[Dict[str, str], Dict[str, str]]
        ] = None  # (joint clean → usd path, link clean → usd path)

    # ------------------------------------------------------------------
    # Clean-name translation (offline pxr — same layer as ArtVIP)
    # ------------------------------------------------------------------

    def _clean_name_maps(self) -> Tuple[Dict[str, str], Dict[str, str]]:
        """(joint, link) ``clean leaf name → USD prim path`` maps.

        For a rigid prop the joint map is empty; the link map carries the
        single ``RigidBodyAPI`` root body.
        """
        if self._name_maps is not None:
            return self._name_maps
        self._ensure_assets()
        from pxr import Usd, UsdPhysics

        try:
            stage = Usd.Stage.Open(str(self.description_file))
        except Exception as exc:  # noqa: BLE001 — surfaced as articulation error
            raise ArticulationError(
                f"Cannot open USD stage {self.description_file} to resolve "
                f"clean joint/link names: {type(exc).__name__}: {exc}"
            ) from exc

        prims = list(stage.Traverse())
        joint_prims = [
            prim
            for prim in prims
            if prim.IsA(UsdPhysics.RevoluteJoint) or prim.IsA(UsdPhysics.PrismaticJoint)
        ]
        link_prims = [
            prim for prim in prims if prim.HasAPI(UsdPhysics.RigidBodyAPI)
        ]
        self._name_maps = (
            dict(zip(usd_clean_names(joint_prims), (str(prim.GetPath()) for prim in joint_prims))),
            dict(zip(usd_clean_names(link_prims), (str(prim.GetPath()) for prim in link_prims))),
        )
        return self._name_maps

    def _to_runtime_name(self, name: str, kind: str) -> str:
        """Clean *name* → the USD path name the built entity carries."""
        if name.startswith("/"):
            return name
        clean_to_path = self._clean_name_maps()[0 if kind == "joint" else 1]
        usd_path = clean_to_path.get(name)
        if usd_path is None:
            raise ArticulationError(
                f"{kind.capitalize()} name not found on the USD stage of "
                f"{self.name!r}: {name!r}. "
                f"Available clean {kind} names: {sorted(clean_to_path)}"
            )
        return usd_path

    # Public (offline) listing helpers -------------------------------

    def clean_name_of(self, runtime_name: str, kind: str = "joint") -> str:
        """USD path name (runtime/joint-record form) → clean leaf name."""
        path_to_clean = {
            path: clean
            for clean, path in self._clean_name_maps()[0 if kind == "joint" else 1].items()
        }
        return path_to_clean.get(runtime_name, runtime_name)

    def list_joint_names(self, entity=None) -> List[str]:
        """Moving joint names of this prop — **empty** (rigid, no articulation)."""
        return sorted(self._clean_name_maps()[0])

    def list_link_names(self, entity=None) -> List[str]:
        """Clean (task-facing) link names (the single root body)."""
        return sorted(self._clean_name_maps()[1])

    # ------------------------------------------------------------------
    # Geometry (offline FK, box proxy — degenerates to the whole-prop box)
    # ------------------------------------------------------------------

    def _load_link_meshes_at_reference(self):
        """The root body's box-proxy mesh at the authored pose (offline FK)."""
        self._ensure_assets()
        return usd_link_meshes_at_config(self.description_file, self.reference_qpos)

    def _load_link_local_meshes_at_reference(self):
        """The root body's box in its own frame (offline FK, link-local)."""
        self._ensure_assets()
        return usd_link_meshes_at_config(
            self.description_file, self.reference_qpos, link_local=True,
        )

    # ------------------------------------------------------------------
    # Scene loading (add_stage)
    # ------------------------------------------------------------------

    def load_into_scene(
        self,
        world: "GenesisWorld",
        pos=(0.0, 0.0, 0.0),
        quat=(1.0, 0.0, 0.0, 0.0),
        name_override=None,
        batch_fixed_verts=False,
    ):
        """Load the prop into the scene (``gs.morphs.USD`` + ``add_stage``).

        The packaged stage carries ``UsdPhysics.RigidBodyAPI`` on its root
        (authored at packaging), so ``add_stage`` collapses it into exactly
        **one** entity (asserted) — welded when *fixed* (default), free
        otherwise.

        Raises:
            ArticulationError: If the stage splits into a number of entities
                other than one (a broken/over-collided repackage).
        """
        import genesis as gs

        # Patch Genesis's z3 collision-bitmask synthesis before the USD is
        # parsed: dense FilteredPairsAPI / contact-exclude assets otherwise
        # spin z3 for minutes per parse.  The constructive fast path solves
        # them in milliseconds (idempotent, no-op without z3).
        from unienv_genesis_collection import genesis_compat

        genesis_compat.install()

        self._ensure_assets()
        if name_override is not None:
            logger.warning(
                "SimReadyWarehouseProp %r: name_override=%r is ignored — "
                "scene.add_stage does not take an entity name; the entity is "
                "named after the USD root prim.",
                self.name,
                name_override,
            )
        morph = gs.morphs.USD(
            file=str(self.description_file),
            scale=self._morph_scale,
            pos=pos,
            quat=quat,
            fixed=self.fixed,
            batch_fixed_verts=batch_fixed_verts,
        )
        entities = world.scene.add_stage(morph)
        if len(entities) != 1:
            raise ArticulationError(
                f"SimReady Warehouse stage {self.description_file} split into "
                f"{len(entities)} entities; a packaged rigid prop must "
                "collapse into one (RigidBodyAPI on the root, packaged)."
            )
        return entities[0]

    # ------------------------------------------------------------------
    # Name-translating overrides over the entity-backed queries
    # ------------------------------------------------------------------

    def resolve_joint_dofs(self, entity, joint_name: str) -> List[int]:
        from unienv_genesis_collection.objects.articulated_object import resolve_joint_dofs

        return resolve_joint_dofs(entity, self._to_runtime_name(joint_name, "joint"))

    def resolve_link_index(self, entity, link_name: str) -> int:
        from unienv_genesis_collection.objects.articulated_object import resolve_link_index

        return resolve_link_index(entity, self._to_runtime_name(link_name, "link"))

    def get_dofs_position(self, entity, joint_name: str, envs_idx=None):
        dofs_idx = self.resolve_joint_dofs(entity, joint_name)
        return entity.get_dofs_position(dofs_idx_local=dofs_idx, envs_idx=envs_idx)

    def set_dofs_position(
        self, entity, position, joint_name: str, envs_idx=None, zero_velocity=True
    ):
        dofs_idx = self.resolve_joint_dofs(entity, joint_name)
        entity.set_dofs_position(
            position,
            dofs_idx_local=dofs_idx,
            envs_idx=envs_idx,
            zero_velocity=zero_velocity,
        )

    def get_joint_limits(self, entity, joint_name: str, envs_idx=None):
        return super().get_joint_limits(
            entity, self._to_runtime_name(joint_name, "joint"), envs_idx=envs_idx,
        )

    def get_link_pose(self, entity, link_name: str, envs_idx=None):
        from unienv_genesis_collection.objects.articulated_object import resolve_link_index

        link_idx = resolve_link_index(entity, self._to_runtime_name(link_name, "link"))
        position = entity.get_links_pos(
            links_idx_local=[link_idx], envs_idx=envs_idx, relative=True,
        ).detach().squeeze(-2)
        quaternion = entity.get_links_quat(
            links_idx_local=[link_idx], envs_idx=envs_idx, relative=True,
        ).detach().squeeze(-2)
        return position, quaternion

    def list_part_grasping_candidates(
        self,
        entity,
        link_name: str,
        gripper_width: float,
        gripper_depth: float = 0.01,
        part_aliases: Optional[Mapping[str, str]] = None,
        rng=None,
        envs_idx=None,
    ):
        resolved_name = (
            part_aliases.get(link_name, link_name) if part_aliases is not None else link_name
        )
        return super().list_part_grasping_candidates(
            entity,
            self._to_runtime_name(resolved_name, "link"),
            gripper_width,
            gripper_depth=gripper_depth,
            part_aliases=None,
            rng=rng,
            envs_idx=envs_idx,
        )

    def _clean_lookup(self, name: str) -> str:
        """Normalise a link name to the *clean* form the FK geometry is keyed by.

        The offline FK dicts (base-link and link-local) are keyed by clean
        leaf names; ``"/"``-prefixed runtime paths are mapped back through
        the name layer so both spellings address the same link.
        """
        if name.startswith("/"):
            return self.clean_name_of(name, "link")
        return name

    def get_link_local_bounding_box(self, link_name: str):
        return super().get_link_local_bounding_box(self._clean_lookup(link_name))

    def _part_grasp_bounding_box(self, link_name: str):
        return super()._part_grasp_bounding_box(self._clean_lookup(link_name))


