"""NVIDIA SimReady Warehouse rigid props as :class:`ArticulatedObject` descriptors.

The NVIDIA Physical AI SimReady Warehouse OpenUSD dataset
(`nvidia/PhysicalAI-SimReady-Warehouse-01
<https://huggingface.co/datasets/nvidia/PhysicalAI-SimReady-Warehouse-01>`_)
ships **753 OpenUSD assets** for an industrial warehouse environment,
enumerated by a CSV catalog.  The collection hosts a repackaged subset
(its "Prop general" + hand-manipulation classes) on its Hugging Face
assets repo under ``objects/simready_warehouse/<object_id>/``, one
self-contained directory per object::

    objects/simready_warehouse/cardbox_c1/cardbox_c1.usd
    objects/simready_warehouse/cardbox_c1/materials/textures/*.png

**Rigid props — no articulation upstream.**  The dataset ships colliders
only ("USDPhysics Colliders applied, but no Rigid Bodies are applied"; the
README's Isaac recipe is *select the asset → add Rigid Body*).  Packaging
performs that authoring step offline: ``UsdPhysics.RigidBodyAPI`` is applied
on the object's root payload prim (``/RootNode``), which makes
``scene.add_stage`` collapse the prop into exactly **one** rigid entity
(verified — without it, per-prim ``CollisionAPI`` colliders parse as one
entity each, and ``ArticulationRootAPI`` alone yields no entity at all).
The packaged stage is the upstream ``<Asset>_physics.usd`` overlay variant
(renamed to ``<object_id>.usd``; it sublayers the visual layer and carries
the convex-hull colliders over the same prim paths).

Jointless is fine: the descriptor is a member of the *articulated* family
with an empty joint set — the offline FK degenerates to the whole-stage
box of the single root body, ``list_joint_names()`` returns ``[]``, and
the entity is welded/fixed by default (``fixed=False`` makes it a
free-floating dynamic rigid body).  ``SimReadyWarehouseProp`` therefore
mirrors :class:`~unienv_genesis_collection.objects.hub_objects.articulated.ArtVIPFurniture`
minus the moving-joint contract.

**Materials — mandatory adaptation.**  Upstream shading is OmniPBR MDL
(local ``materials/*.mdl`` recipes or the inline OmniPBR graph), which
usd-core cannot read; packaging rewrites every graph into native
``UsdPreviewSurface`` + ``UsdUVTexture`` via
:func:`~unienv_genesis_collection.utils.usd_conversions.convert_mdl_to_preview_surface`
and drops the ``materials/*.mdl`` recipes (their textures are packaged).

**Units.**  Upstream ``metersPerUnit`` is mixed (0.01 / 0.0099999… / 1.0).
The packaged stages are normalised to 1.0 by folding the old factor into the
root prim's linear map (a root-level uniform scale) — identical world size,
one unit convention, so Genesis's ``_meter_scale`` (applied to every
composed transform) becomes a no-op and the offline FK matches the runtime
frame exactly.

**License — CC BY 4.0, attribution.**  The dataset card tags
``license:cc-by-4.0`` but the archive commits no LICENSE file; attribution
("Physical AI SimReady Warehouse Dataset, © NVIDIA Corporation, CC BY 4.0")
ships next to the assets (``LICENSE``/``README.md`` generated by the prep
script) — see ``docs/articulated_rooms.md`` for the caveat note.

The catalog ships with the assets as ``objects/simready_warehouse/catalog.json``.

Typical usage::

    from unienv_genesis_collection.objects import (
        SimReadyWarehouseProp, make_simready_warehouse_pool,
    )

    box = SimReadyWarehouseProp("prop_cardbox_c1")
    pool = make_simready_warehouse_pool(tags="prop", n=4,
                                        rng=torch.Generator().manual_seed(0))
"""

