"""ArtVIP USD articulated furniture as :class:`ArticulatedObject` descriptors.

The ArtVIP dataset (`X-Humanoid/ArtVIP
<https://huggingface.co/datasets/X-Humanoid/ArtVIP>`_) ships **articulated
USD furniture** (fridges, cabinets, washing machines, …) exported from Isaac
Sim.  The collection hosts a repackaged subset on its Hugging Face assets
repo under ``objects/artvip/<object_id>/``, one self-contained directory per
object::

    objects/artvip/refrigerator_fridge_4/refrigerator_fridge_4.usd
    objects/artvip/refrigerator_fridge_4/resource/material.usd
    objects/artvip/refrigerator_fridge_4/resource/v_0/link_default_0.usd
    objects/artvip/refrigerator_fridge_4/resource/img/*.png             # textures

Furniture is loaded via ``gs.morphs.USD`` + ``scene.add_stage`` — the only
composite-entity loader (per-object stages split into exactly **one**
``RigidEntity``, asserted at load).  ``fixed=self.fixed`` overrides the
articulation root's fixity like the URDF path (``robot_node.py`` precedent).

**Joint/link name sanitisation.**  Genesis names USD joints and links by
their **full prim path** (``/root/E_door1_1/RevoluteJoint_skbx_25_right``),
which is unwieldy and asset-layout-dependent.  The descriptor maintains a
clean-name translation layer: task-facing names are the USD *leaf* prim
names (``RevoluteJoint_skbx_25_right``, ``E_door1_1``) — built lazily
offline from the stage with ``pxr`` (no Genesis scene), with ambiguous
leaves disambiguated by the parent-chain suffix.  Names already in
path form (``"/"``-prefixed) pass through unchanged, so both spellings
address the same joint.  ``reference_qpos`` **takes clean names** (the
offline FK walker keys by leaf name).

The catalog ships with the assets as ``objects/artvip/catalog.json``
(``Catalog``-schema: language annotations + tags, optional
``standing_quaternion``).

Typical usage::

    from unienv_genesis_collection.objects import (
        ArtVIPFurniture, make_artvip_pool,
    )

    fridge = ArtVIPFurniture("refrigerator_fridge_4")
    pool = make_artvip_pool(tags="kitchen", n=4,
                            rng=torch.Generator().manual_seed(0))
"""

