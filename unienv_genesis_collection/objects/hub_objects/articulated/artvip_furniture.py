logger = logging.getLogger(__name__)

# Path of the ArtVIP collection relative to the assets root (POSIX separators).
ARTVIP_ASSETS_ROOT = "objects/artvip"

# The catalog (language annotations + tags per object) ships with the assets
# as ``objects/artvip/catalog.json``; it is generated by
# ``scripts/prepare_artvip_assets.py`` from the ArtVIP category templates.
ARTVIP_CATALOG_PATH = f"{ARTVIP_ASSETS_ROOT}/catalog.json"


def get_artvip_catalog() -> Dict[str, ObjectInfo]:
    """Return the ArtVIP catalog (object id → :class:`ObjectInfo`).

    Loaded from ``objects/artvip/catalog.json`` in the assets folder
    (downloaded on first use) and cached.
    """
    return load_catalog(ARTVIP_CATALOG_PATH)


def list_artvip_objects(
    *,
    tags: Optional[Union[str, Iterable[str]]] = None,
    contains: Optional[str] = None,
) -> List[str]:
    """Return ArtVIP object ids, optionally filtered by tags and/or substring.

    Works fully offline — only the generated catalog is consulted.

    Args:
        tags: A tag or iterable of tags.  Only objects carrying **all** of
            them are returned (e.g. ``"kitchen"``, ``"articulated"``).
        contains: Case-insensitive substring to filter ids by (e.g.
            ``"refrigerator"``).  Combinable with *tags*.

    Returns:
        Sorted list of object ids.
    """
    if tags is None:
        wanted: FrozenSet[str] = frozenset()
    elif isinstance(tags, str):
        wanted = frozenset((tags,))
    else:
        wanted = frozenset(tags)
    needle = contains.lower() if contains is not None else None
    return sorted(
        object_id
        for object_id, info in get_artvip_catalog().items()
        if wanted <= info.tags
        and (needle is None or needle in object_id.lower())
    )


# ---------------------------------------------------------------------------
# ArtVIPFurniture
# ---------------------------------------------------------------------------

class ArtVIPFurniture(HubAssetArticulatedObject):
    """ArtVIP USD articulated furniture loaded via ``scene.add_stage``.

    Unlike the URDF/MJCF siblings, USD stages load into a *composite*
    entity: the USD morph may fan out to multiple entities, but an ArtVIP
    per-object stage is one rigid articulation, and :meth:`load_into_scene`
    asserts exactly one returned entity.  ``add_stage`` takes no entity
    ``name=`` (it fans entities out of the stage itself), so unlike the
    other hub families a ``name_override`` can **not** be honoured — the
    argument is accepted (for the shared ``load_into_scene`` signature used
    by e.g. ``RoomBuilder.reload``) and warns-and-ignores; the returned
    entity carries the USD root prim's name.

    Joint/link names: Genesis addresses USD joints/links by full prim path;
    this descriptor exposes task-facing **clean names** (the leaf prim
    tokens) through a lazy, offline name-translation layer — see the module
    docstring.  ``reference_qpos`` and every joint/link query take the clean
    names; ``"/"``-prefixed USD paths are accepted too (pass-through).

    Construction is offline-safe; assets are downloaded lazily on first
    scene load or geometry query and verified for completeness (the pxr
    layer stack + ``resource/`` textures must all be present locally).

    Args:
        object_id: Catalog id, e.g. ``"refrigerator_fridge_4"``.  See
            :func:`get_artvip_catalog` or :func:`list_artvip_objects`.
        scale: Uniform scale factor.  USD morphs only support uniform
            (scalar) scaling — per-axis tuples are rejected (scalar-only,
            like the MJCF family).
        name: Technical identifier; defaults to *object_id*.
        fixed: Whether the furniture is immovable (the morph ``fixed``
            flag; USD morphs have one — overrides the articulated root).
        reference_qpos: **Clean** joint name → position at the reference
            configuration used by the offline union bbox (default all-zero
            = the authored closed pose).
        language_annotations: Override the catalog's default annotations.
        standing_quaternion: Optional ``(w, x, y, z)`` orientation used by
            ``set_pos_3d``/room placements instead of the identity.
            Defaults to the catalog's ``standing_quaternion`` metadata
            when present.
        description_file_name: Override the packaged description file name
            (default ``"<object_id>.usd"``).  The packaging step renames
            the upstream ``model_<id>.usd``; the override exists for
            locally-authored assets/tests (e.g. ``"<id>.usda"``).
    """

    def __init__(
        self,
        object_id: str,
        scale: float = 1.0,
        name: Optional[str] = None,
        fixed: bool = True,
        reference_qpos: Optional[Dict[str, float]] = None,
        language_annotations: Optional[Sequence[str]] = None,
        standing_quaternion: Optional[Sequence[float]] = None,
        description_file_name: Optional[str] = None,
    ):
        catalog = get_artvip_catalog()
        info = catalog.get(object_id)
        if info is None:
            raise KeyError(
                f"Unknown ArtVIP object id: {object_id!r}. "
                f"See list_artvip_objects() for the {len(catalog)} available ids."
            )
        if isinstance(scale, tuple):
            raise ValueError(
                "ArtVIPFurniture only supports uniform (scalar) scaling: "
                "per-axis scale is a gs.morphs.Mesh-only feature."
            )
        super().__init__(
            asset_relative_dir=f"{ARTVIP_ASSETS_ROOT}/{object_id}",
            description_file_name=description_file_name or f"{object_id}.usd",
            name=name or object_id,
            fixed=fixed,
            reference_qpos=reference_qpos,
            language_annotations=(
                language_annotations
                if language_annotations is not None
                else info.language_annotations
            ),
            scale=scale,
            standing_quaternion=(
                standing_quaternion
                if standing_quaternion is not None
                else info.standing_quaternion
            ),
        )
        self.object_id = object_id
        self.info = info
        self._morph_scale = float(scale)
        # Lazy (offline pxr) clean-name translation layer, built on first use.
        self._name_maps: Optional[
            Tuple[Dict[str, str], Dict[str, str]]
        ] = None  # (joint clean → usd path, link clean → usd path)

    # ------------------------------------------------------------------
    # Clean-name translation (offline pxr — plan D2)
    # ------------------------------------------------------------------

    def _clean_name_maps(self) -> Tuple[Dict[str, str], Dict[str, str]]:
        """(joint, link) ``clean leaf name → USD prim path`` maps.

        Built lazily from the stage with ``pxr`` (offline — no Genesis
        scene; assets are ensured first).  The same walk the offline FK
        helper does, so its keys agree with the geometry's keys.
        """
        if self._name_maps is not None:
            return self._name_maps
        self._ensure_assets()
        from pxr import Usd, UsdPhysics

        try:
            stage = Usd.Stage.Open(str(self.description_file))
        except Exception as exc:  # noqa: BLE001 — surfaced as articulation error
            raise ArticulationError(
                f"Cannot open USD stage {self.description_file} to resolve "
                f"clean joint/link names: {type(exc).__name__}: {exc}"
            ) from exc

        prims = list(stage.Traverse())
        joint_prims = [
            prim
            for prim in prims
            if prim.IsA(UsdPhysics.RevoluteJoint) or prim.IsA(UsdPhysics.PrismaticJoint)
        ]
        link_prims = [
            prim for prim in prims if prim.HasAPI(UsdPhysics.RigidBodyAPI)
        ]
        self._name_maps = (
            dict(zip(usd_clean_names(joint_prims), (str(prim.GetPath()) for prim in joint_prims))),
            dict(zip(usd_clean_names(link_prims), (str(prim.GetPath()) for prim in link_prims))),
        )
        return self._name_maps

    def _to_runtime_name(self, name: str, kind: str) -> str:
        """Clean *name* → the USD path name the built entity carries.

        ``"/"``-prefixed names (already runtime form) pass through.  Unknown
        clean names raise :class:`ArticulationError` listing the available
        **clean** names.
        """
        if name.startswith("/"):
            return name
        clean_to_path = self._clean_name_maps()[0 if kind == "joint" else 1]
        usd_path = clean_to_path.get(name)
        if usd_path is None:
            raise ArticulationError(
                f"{kind.capitalize()} name not found on the USD stage of "
                f"{self.name!r}: {name!r}. "
                f"Available clean {kind} names: {sorted(clean_to_path)}"
            )
        return usd_path

    # Public (offline) listing helpers -------------------------------

    def clean_name_of(self, runtime_name: str, kind: str = "joint") -> str:
        """USD path name (runtime/joint-record form) → clean leaf name.

        The inverse of :meth:`_to_runtime_name`; an unknown path (e.g. a
        joint Genesis granted but the leaf-collapsed walk does not track)
        passes through unchanged.
        """
        path_to_clean = {
            path: clean
            for clean, path in self._clean_name_maps()[0 if kind == "joint" else 1].items()
        }
        return path_to_clean.get(runtime_name, runtime_name)

    def list_joint_names(self, entity=None) -> List[str]:
        """Clean (task-facing) joint names of this object.

        Offline via the stage walk — no built entity required (the
        *entity* argument is accepted for API parity and ignored: the
        offline walk enumerates exactly the moving joints the load grants).
        """
        return sorted(self._clean_name_maps()[0])

    def list_link_names(self, entity=None) -> List[str]:
        """Clean (task-facing) link names of this object."""
        return sorted(self._clean_name_maps()[1])

    # ------------------------------------------------------------------
    # Geometry (offline FK, box proxy)
    # ------------------------------------------------------------------

    def _load_link_meshes_at_reference(self):
        """Per-link box-proxy meshes at the reference configuration (offline FK).

        Uses :func:`~unienv_genesis_collection.objects.articulated_object.usd_link_meshes_at_config`
        (pxr UsdPhysics FK walker — no Genesis scene); the result feeds the
        union :meth:`get_local_bounding_box`.  Assets are ensured first so
        the stage's layers exist locally.
        """
        self._ensure_assets()
        return usd_link_meshes_at_config(self.description_file, self.reference_qpos)

    def _load_link_local_meshes_at_reference(self):
        """Per-link box-proxy meshes in each link's own frame (offline FK).

        Part-grasp enumeration frame for
        :meth:`~unienv_genesis_collection.objects.articulated_object.ArticulatedObject.list_part_grasping_candidates`:
        the link's visual-subtree AABB without the link's FK transform —
        configuration-independent, via
        :func:`~unienv_genesis_collection.objects.articulated_object.usd_link_meshes_at_config`
        with ``link_local=True``.
        """
        self._ensure_assets()
        return usd_link_meshes_at_config(
            self.description_file, self.reference_qpos, link_local=True,
        )

    # ------------------------------------------------------------------
    # Scene loading (add_stage)
    # ------------------------------------------------------------------

    def load_into_scene(
        self,
        world: "GenesisWorld",
        pos=(0.0, 0.0, 0.0),
        quat=(1.0, 0.0, 0.0, 0.0),
        name_override=None,
        batch_fixed_verts=False,
    ):
        """Load the USD stage into the scene (``gs.morphs.USD`` + ``add_stage``).

        ``add_stage`` splits composite stages into one entity per rigid
        component; an ArtVIP per-object stage must split into exactly one
        (asserted), and it takes no entity ``name=`` — so *name_override*
        is accepted for signature compatibility and **warned-and-ignored**
        (see the class docstring).

        Args:
            world: ``GenesisWorld`` with an unbuilt scene.
            pos: World position ``(x, y, z)``.
            quat: World orientation ``(w, x, y, z)``.
            name_override: Accepted but ignored (warned) — ``add_stage`` has
                no entity ``name=``; the entity carries the USD root name.
            batch_fixed_verts: Enable per-env position overrides for fixed
                entities in batched worlds (significant memory cost).

        Returns:
            The single Genesis rigid entity the stage splits into.

        Raises:
            ArticulationError: If the stage splits into a number of entities
                other than one (a broken/multi-component stage).
        """
        import genesis as gs

        # Patch Genesis's z3 collision-bitmask synthesis before the USD is
        # parsed: dense FilteredPairsAPI / contact-exclude assets otherwise
        # spin z3 for minutes per parse.  The constructive fast path solves
        # them in milliseconds (idempotent, no-op without z3).
        from unienv_genesis_collection import genesis_compat

        genesis_compat.install()

        self._ensure_assets()
        if name_override is not None:
            logger.warning(
                "ArtVIPFurniture %r: name_override=%r is ignored — "
                "scene.add_stage does not take an entity name; the entity is "
                "named after the USD root prim.",
                self.name,
                name_override,
            )
        morph = gs.morphs.USD(
            file=str(self.description_file),
            scale=self._morph_scale,
            pos=pos,
            quat=quat,
            fixed=self.fixed,
            batch_fixed_verts=batch_fixed_verts,
        )
        entities = world.scene.add_stage(morph)
        if len(entities) != 1:
            raise ArticulationError(
                f"ArtVIPUSD stage {self.description_file} split into "
                f"{len(entities)} entities; an ArtVIP per-object stage must "
                "be a single rigid component."
            )
        return entities[0]

    # ------------------------------------------------------------------
    # Name-translating overrides over the entity-backed queries
    # ------------------------------------------------------------------

    def resolve_joint_dofs(self, entity, joint_name: str) -> List[int]:
        from unienv_genesis_collection.objects.articulated_object import resolve_joint_dofs

        return resolve_joint_dofs(entity, self._to_runtime_name(joint_name, "joint"))

    def resolve_link_index(self, entity, link_name: str) -> int:
        from unienv_genesis_collection.objects.articulated_object import resolve_link_index

        return resolve_link_index(entity, self._to_runtime_name(link_name, "link"))

    def get_dofs_position(self, entity, joint_name: str, envs_idx=None):
        # Same contract as ArticulatedObject.get_dofs_position, with the
        # clean-name translation (the base implementation resolves the
        # raw name against the entity directly — USD runtime names are paths).
        dofs_idx = self.resolve_joint_dofs(entity, joint_name)
        return entity.get_dofs_position(dofs_idx_local=dofs_idx, envs_idx=envs_idx)

    def set_dofs_position(
        self, entity, position, joint_name: str, envs_idx=None, zero_velocity=True
    ):
        dofs_idx = self.resolve_joint_dofs(entity, joint_name)
        entity.set_dofs_position(
            position,
            dofs_idx_local=dofs_idx,
            envs_idx=envs_idx,
            zero_velocity=zero_velocity,
        )

    def get_joint_limits(self, entity, joint_name: str, envs_idx=None):
        # ArticulatedObject.get_joint_limits with the clean name translated
        # to the runtime path (unbounded/degenerate-limit errors unchanged —
        # they report the runtime name, which the caller glosses over).
        return super().get_joint_limits(
            entity, self._to_runtime_name(joint_name, "joint"), envs_idx=envs_idx,
        )

    def get_link_pose(self, entity, link_name: str, envs_idx=None):
        from unienv_genesis_collection.objects.articulated_object import resolve_link_index

        link_idx = resolve_link_index(entity, self._to_runtime_name(link_name, "link"))
        position = entity.get_links_pos(
            links_idx_local=[link_idx], envs_idx=envs_idx, relative=True,
        ).detach().squeeze(-2)
        quaternion = entity.get_links_quat(
            links_idx_local=[link_idx], envs_idx=envs_idx, relative=True,
        ).detach().squeeze(-2)
        return position, quaternion

    def list_part_grasping_candidates(
        self,
        entity,
        link_name: str,
        gripper_width: float,
        gripper_depth: float = 0.01,
        part_aliases: Optional[Mapping[str, str]] = None,
        rng=None,
        envs_idx=None,
    ):
        resolved_name = (
            part_aliases.get(link_name, link_name) if part_aliases is not None else link_name
        )
        return super().list_part_grasping_candidates(
            entity,
            self._to_runtime_name(resolved_name, "link"),
            gripper_width,
            gripper_depth=gripper_depth,
            part_aliases=None,
            rng=rng,
            envs_idx=envs_idx,
        )

    def get_link_local_bounding_box(self, link_name: str):
        return super().get_link_local_bounding_box(
            self._to_runtime_name(link_name, "link"),
        )


