"""Amazon Berkeley Objects (ABO) as :class:`ManipulatableObject` descriptors.

The assets are a repackaged copy of the
`Amazon Berkeley Objects dataset <https://amazon-berkeley-objects.s3.us-east-1.amazonaws.com/index.html>`_
— 7,953 modelled Amazon.com products with materials, **CC BY 4.0** (Amazon.com
relicensed ABO from CC BY-NC 4.0 in mid-2023; the old license file is no
longer served) — hosted on the collection's Hugging Face assets repo under
``objects/abo/<object_id>/``.  Each object directory is self-contained::

    objects/abo/<id>/model.obj             # Z-up visual mesh
    objects/abo/<id>/material.mtl
    objects/abo/<id>/texture.png
    objects/abo/<id>/model.glb             # original GLB (only if kept)

where ``<id>`` is the dataset's ``3dmodel_id`` (e.g. ``B07B4Z9BS4``).

The dataset's GLBs are glTF 2.0 binary, **Y-up** and metric (metres), with the
product standing on the ``Y=0`` plane.  ``scripts/prepare_abo_assets.py``
bakes the Y-up → Z-up rotation into ``model.obj`` (the same
``(X, Y, Z) → (X, -Z, Y)`` mapping Genesis applies to Y-up formats) instead of
shipping the GLB, so the mesh frame, the trimesh bounding-box frame and the
placed frame agree and no ``standing_quaternion`` is needed.

Objects are loaded with ``gs.morphs.Mesh`` and the texture bound explicitly, so
rendering does not depend on Genesis parsing the MTL.  No collision
decomposition ships with the dataset: Genesis's own convex decomposition
(``convexify``) of the scanned, non-watertight mesh provides the collision
geometry, and the mass is derived from it.

Assets are fetched lazily: the object directory is downloaded (and verified
for completeness) on first scene load or geometry query.  Per-object metadata
— language annotations (broad → detailed) and tags, kept in separate fields —
ships with the assets as ``objects/abo/catalog.json`` (a single small file,
fetched on first catalog access); the ``box_gripper_graspable`` tag marks
objects whose smallest mesh extent fits a ~8.5 cm parallel-jaw gripper.

Typical usage::

    from unienv_genesis_collection.objects import ABOObject, make_abo_pool

    chair = ABOObject("B07B4Z9BS4")
    pool = make_abo_pool(tags="office_furniture_lighting", n=5,
                         rng=torch.Generator().manual_seed(0))
"""

from __future__ import annotations

from pathlib import Path
from typing import (
    Dict,
    FrozenSet,
    Iterable,
    List,
    Optional,
    Sequence,
    Tuple,
    Union,
    TYPE_CHECKING,
)

import torch

from unienv_genesis_collection.objects.hub_objects.catalog import (
    ObjectInfo,
    load_catalog,
)
from unienv_genesis_collection.objects.hub_objects.hub_asset_object import (
    HubAssetMeshObject,
)

if TYPE_CHECKING:
    from unienv_genesis.world.genesis_world import GenesisWorld

__all__ = [
    "ABO_ASSETS_ROOT",
    "ABO_CATALOG_PATH",
    "get_abo_catalog",
    "ABOObject",
    "list_abo_objects",
    "make_abo_pool",
]

# Path of the ABO collection relative to the assets root (POSIX separators).
ABO_ASSETS_ROOT = "objects/abo"

# The catalog (language annotations + tags per object) ships with the assets
# as ``objects/abo/catalog.json``; it is generated by
# ``scripts/prepare_abo_assets.py`` from the dataset's listings metadata.
ABO_CATALOG_PATH = f"{ABO_ASSETS_ROOT}/catalog.json"


def get_abo_catalog() -> Dict[str, ObjectInfo]:
    """Return the ABO catalog (object id → :class:`ObjectInfo`).

    Loaded from ``objects/abo/catalog.json`` in the assets folder (downloaded
    on first use) and cached.  Annotations are ordered from broad to detailed
    (product type, catalog node, cleaned ``item_name``, cleaned
    ``bullet_point``s); tags carry the normalized product type / catalog node
    labels plus ``box_gripper_graspable`` when the object's smallest mesh
    bounding-box dimension fits a ~8.5 cm parallel-jaw gripper (computed by
    ``scripts/prepare_abo_assets.py``; for a per-pose mesh check at runtime use
    :meth:`ManipulatableObject.is_box_gripper_graspable`).
    """
    return load_catalog(ABO_CATALOG_PATH)


def list_abo_objects(
    *,
    tags: Optional[Union[str, Iterable[str]]] = None,
    contains: Optional[str] = None,
) -> List[str]:
    """Return ABO object ids, optionally filtered by tags and/or substring.

    Works fully offline — only the generated catalog is consulted.

    Args:
        tags: A tag or iterable of tags.  Only objects carrying **all** of
            them are returned (e.g. ``"office_furniture_lighting"``,
            ``"box_gripper_graspable"``).
        contains: Case-insensitive substring to filter ids by (e.g. ``"B07"``).
            Combinable with *tags*.

    Returns:
        Sorted list of object ids.
    """
    if tags is None:
        wanted: FrozenSet[str] = frozenset()
    elif isinstance(tags, str):
        wanted = frozenset((tags,))
    else:
        wanted = frozenset(tags)
    needle = contains.lower() if contains is not None else None
    return [
        object_id
        for object_id, info in get_abo_catalog().items()
        if wanted <= info.tags
        and (needle is None or needle in object_id.lower())
    ]


# ---------------------------------------------------------------------------
# ABOObject
# ---------------------------------------------------------------------------

class ABOObject(HubAssetMeshObject):
    """An Amazon Berkeley Object loaded into Genesis via its OBJ mesh.

    Inherits the trimesh-based bounding-box and grasp-candidate machinery from
    :class:`MeshObject` (pointed at the object's prepared ``model.obj``), but
    overrides :meth:`load_into_scene` so the Z-up mesh's texture is bound
    explicitly and Genesis's convex decomposition provides the collision
    geometry (ABO ships no collision hulls).

    Construction is offline-safe; assets are downloaded lazily on first scene
    load or geometry query and verified for completeness.

    Args:
        object_id: Catalog id (the dataset's ``3dmodel_id``).  See
            :func:`get_abo_catalog` or :func:`list_abo_objects`.
        scale: Uniform scalar or per-axis ``(sx, sy, sz)`` scale factor
            (``gs.morphs.Mesh`` supports both).
        name: Technical identifier; defaults to *object_id*.
        fixed: Whether the object is immovable.
        language_annotations: Override the catalog's default annotations.
        standing_quaternion: Optional ``(w, x, y, z)`` orientation used by
            :meth:`set_pos_3d` instead of the identity when the object is
            placed without randomisation.  ABO meshes are already Z-up and
            upright (the product stands on the ``Z=0`` plane), so this is
            ``None`` unless a catalog entry or the caller overrides it.
    """

    def __init__(
        self,
        object_id: str,
        scale: Union[float, Tuple[float, float, float]] = 1.0,
        name: Optional[str] = None,
        fixed: bool = False,
        language_annotations: Optional[Sequence[str]] = None,
        standing_quaternion: Optional[Sequence[float]] = None,
    ):
        catalog = get_abo_catalog()
        info = catalog.get(object_id)
        if info is None:
            raise KeyError(
                f"Unknown ABO object id: {object_id!r}. "
                f"See list_abo_objects() for the {len(catalog)} available ids."
            )
        super().__init__(
            asset_relative_dir=f"{ABO_ASSETS_ROOT}/{object_id}",
            mesh_file_name="model.obj",
            scale=scale,
            name=name or object_id,
            fixed=fixed,
            language_annotations=(
                language_annotations
                if language_annotations is not None
                else info.language_annotations
            ),
            visual_texture_file_name="texture.png",
            standing_quaternion=(
                standing_quaternion
                if standing_quaternion is not None
                else info.standing_quaternion
            ),
        )
        self.object_id = object_id
        self.info = info
        # Scalar scales are passed to the morph as float, per-axis as tuple.
        self._morph_scale: Union[float, Tuple[float, float, float]] = (
            scale if isinstance(scale, tuple) else float(scale)
        )

    def _required_files(self) -> List[Path]:
        """The Z-up visual mesh, its material, and the bound texture."""
        return [
            self.asset_dir / "model.obj",
            self.asset_dir / "material.mtl",
            self.asset_dir / "texture.png",
        ]

    def load_into_scene(
        self,
        world: "GenesisWorld",
        pos=(0.0, 0.0, 0.0),
        quat=(1.0, 0.0, 0.0, 0.0),
        name_override=None,
        batch_fixed_verts=False,
    ):
        import genesis as gs

        self._ensure_assets()
        morph = gs.morphs.Mesh(
            file=str(self.mesh_file),
            scale=self._morph_scale,
            pos=pos,
            quat=quat,
            fixed=self.fixed,
            batch_fixed_verts=batch_fixed_verts,
            # ABO ships no collision hulls; the scanned mesh is non-watertight,
            # so let Genesis's own convex decomposition build one.
            convexify=True,
        )
        # Bound explicitly: the mesh's texture lives in the object directory
        # and Genesis must not need to parse the MTL to find it.
        surface = gs.surfaces.Plastic(
            diffuse_texture=gs.textures.ImageTexture(image_path=self.visual_texture_path),
        )
        return world.scene.add_entity(
            morph,
            surface=surface,
            name=name_override or self.name,
        )


# ---------------------------------------------------------------------------
# Pool building
# ---------------------------------------------------------------------------

def make_abo_pool(
    object_ids: Optional[Sequence[str]] = None,
    *,
    tags: Optional[Union[str, Iterable[str]]] = None,
    contains: Optional[str] = None,
    n: Optional[int] = None,
    rng: Optional[torch.Generator] = None,
    **object_kwargs,
) -> List[ABOObject]:
    """Build a list of :class:`ABOObject` for use as an object pool.

    The result plugs directly into consumers such as
    ``ClutteredTableManager(object_pool=...)``.  Construction does not
    download anything; assets are fetched when the objects are first loaded
    into a scene.

    Args:
        object_ids: Explicit ids to use (order preserved).  Mutually
            exclusive with *tags* / *contains*.
        tags: Filter the catalog by tags (see :func:`list_abo_objects`).
        contains: Filter ids by case-insensitive substring (see
            :func:`list_abo_objects`).  Combinable with *tags*.
        n: If given, sample *n* distinct objects from the selection.
        rng: Optional :class:`torch.Generator` for reproducible sampling.
            When omitted (``None``), the global Torch RNG is used.
        **object_kwargs: Forwarded to every :class:`ABOObject` (e.g.
            ``scale=0.8``).

    Returns:
        List of :class:`ABOObject` descriptors with unique names.

    Raises:
        ValueError: If *object_ids* is combined with *tags* / *contains*,
            or *n* exceeds the number of selected objects.
        KeyError: If an explicit id is not in the catalog.
    """
    if object_ids is not None and (tags is not None or contains is not None):
        raise ValueError("Pass either object_ids or tags/contains, not both.")

    ids = (
        list(object_ids)
        if object_ids is not None
        else list_abo_objects(tags=tags, contains=contains)
    )

    if n is not None:
        if n > len(ids):
            raise ValueError(
                f"Requested {n} objects but only {len(ids)} match the selection."
            )
        # Pin the output device to the generator's device: with a Genesis
        # CUDA default device, an unpinned randperm would create a CUDA tensor
        # from a CPU generator and raise a device-mismatch error.
        perm = torch.randperm(
            len(ids), generator=rng, device=rng.device if rng is not None else None
        )[:n].tolist()
        ids = [ids[i] for i in perm]

    return [ABOObject(object_id, **object_kwargs) for object_id in ids]
