# LightwheelEnv
# ---------------------------------------------------------------------------

class LightwheelEnv(HubAssetMeshObject):
    """A jointless Lightwheel scene stage loaded via ``scene.add_stage``.

    Catalog-driven like :class:`~unienv_genesis_collection.objects.hub_objects.gso_object.GSOObject`
    (the collection's other static, non-articulated Hub asset), but loaded
    through ``gs.morphs.USD`` + ``scene.add_stage`` like the USD furniture
    families.  **No single-entity assertion**: ``add_stage`` on a jointless,
    ``RigidBodyAPI``-less stage merges everything into fixed visual/collision
    geometry in practice, but the meaningful contract here is "loads without
    error" — Apartment alone carries 223 collider subtrees and Genesis is free
    to change how many entities that becomes.

    Construction is offline-safe; assets are downloaded lazily on first scene
    load or geometry query and verified for completeness (the root layer plus
    every file its layer stack references).

    Args:
        object_id: Catalog id, e.g. ``"lightwheel_env_grass"``.  See
            :func:`get_lightwheel_env_catalog` /
            :func:`list_lightwheel_env_objects`.
        scale: Uniform scale factor (scalar only — ``gs.morphs.USD`` has no
            per-axis scale).
        name: Technical identifier; defaults to *object_id*.
        fixed: Whether the environment is immovable.  ``True`` (the default)
            is right for terrains and rooms; ``False`` makes the stage a
            free-floating dynamic body (rarely useful).
        language_annotations: Override the catalog's default annotations.
        standing_quaternion: Optional ``(w, x, y, z)`` orientation used by
            ``set_pos_3d``/placements instead of the identity.  Defaults to
            the catalog's ``standing_quaternion`` metadata when present (all
            shipped environments are authored Z-up, so it is usually absent).
        description_file_name: Override the packaged root layer name
            (default ``"<object_id>.usd"``).
    """

    def __init__(
        self,
        object_id: str,
        scale: float = 1.0,
        name: Optional[str] = None,
        fixed: bool = True,
        language_annotations: Optional[Sequence[str]] = None,
        standing_quaternion: Optional[Sequence[float]] = None,
        description_file_name: Optional[str] = None,
    ):
        catalog = get_lightwheel_env_catalog()
        info = catalog.get(object_id)
        if info is None:
            raise KeyError(
                f"Unknown Lightwheel environment id: {object_id!r}. "
                f"See list_lightwheel_env_objects() for the "
                f"{len(catalog)} available ids."
            )
        if isinstance(scale, tuple):
            raise ValueError(
                "LightwheelEnv only supports uniform (scalar) scaling: "
                "per-axis scale is a gs.morphs.Mesh-only feature."
            )
        super().__init__(
            asset_relative_dir=f"{LIGHTWHEEL_ENV_ASSETS_ROOT}/{object_id}",
            mesh_file_name=description_file_name or f"{object_id}.usd",
            scale=scale,
            name=name or object_id,
            fixed=fixed,
            language_annotations=(
                language_annotations
                if language_annotations is not None
                else info.language_annotations
            ),
            standing_quaternion=(
                standing_quaternion
                if standing_quaternion is not None
                else info.standing_quaternion
            ),
        )
        self.object_id = object_id
        self.info = info
        # The USD root layer (the packaged ``<object_id>.usd``).
        self.description_file: Path = self.asset_dir / (
            description_file_name or f"{object_id}.usd"
        )
        self._morph_scale = float(scale)
        self._local_bbox_cache: Optional["BoxSpace"] = None

    # ------------------------------------------------------------------
    # Asset resolution
    # ------------------------------------------------------------------

    def _required_files(self) -> List[Path]:
        """The root layer + its full pxr layer-stack/texture closure.

        ``required_only=True`` skips asset-valued references that are neither
        USD layers nor images — the bundle's UE-export ``Foo.Foo`` material
        records (Apartment ships 20 of them) exist nowhere in the bundle and
        never will; demanding them would make ``_missing_files()`` permanently
        non-empty (a Hub download on every build, and a permanent
        "incomplete directory" offline).  The packager warn-and-records them
        instead (``packaging_log.json``), and usd-core opens the stage fine.
        """
        from unienv_genesis_collection.objects.hub_objects.articulated.hub_articulated_object import (
            _usd_required_files,
        )

        required: List[Path] = [self.description_file]
        if not self.description_file.is_file():
            return required
        required += _usd_required_files(
            self.description_file, self.asset_dir, required_only=True
        )
        return list(dict.fromkeys(required))

    def _load_trimesh(self) -> "trimesh.Trimesh":
        """Unsupported: ``trimesh`` cannot read USD stages.

        These environments are multi-hundred-MB scene stages (1764 meshes in
        the largest), so there is no trimesh geometry path at all — the
        bounding box comes from pxr (:meth:`get_local_bounding_box`) and
        grasp-candidate machinery does not apply to a terrain/room.
        """
        raise NotImplementedError(
            f"LightwheelEnv {self.name!r} has no trimesh geometry: "
            "trimesh cannot read USD stages and these environments are "
            "multi-hundred-MB scenes.  Use get_local_bounding_box() (pxr "
            "BBoxCache union) instead."
        )

    # ------------------------------------------------------------------
    # Geometry (offline, pxr — the stages are static, so there is no FK)
    # ------------------------------------------------------------------

    def get_local_bounding_box(self) -> "BoxSpace":
        """World AABB of the geometry Genesis actually loads (cached).

        Mirrors the loader's own geometry selection — NOT a
        ``UsdGeom.BBoxCache`` union over the pseudo-root children, which
        over-approximates in both directions (an authored ``extent`` box is
        transformed rigidly, so a rotated thin/diagonal mesh inflates, and
        visual-only subtrees outside any collider inflate the range even when
        ``add_stage`` never instantiates them):

        * *entity prims* — ``RigidBodyAPI``/``CollisionAPI``/
          ``ArticulationRootAPI`` prims, children pruned (the semantics of
          ``genesis.utils.usd.UsdContext.find_all_rigid_entities``: only those
          subtrees become ``RigidEntity`` instances);
        * *per entity* — every visible non-guide ``UsdGeom.Gprim`` of its
          subtree (with instance proxies — the parser's predicate).  Meshes
          contribute their actual ``points`` transformed by their
          local-to-world matrix (point-accurate under rotation + non-uniform
          scale); other gprims fall back to the bound cache's 8-corner box.

        The bound is expressed in the stage's own (metres) frame — the frame
        Genesis reports ``entity.get_vAABB()`` in for a USD entity loaded at
        the identity morph pose — and scaled by ``scale``.  (A Y-up stage is
        mapped onto the Z-up Genesis world exactly like
        ``genesis.utils.usd.UsdContext.compute_transform`` does.)
        """
        if self._local_bbox_cache is None:
            import numpy as np
            from pxr import Usd, UsdGeom, UsdPhysics

            self._ensure_assets()
            stage = Usd.Stage.Open(str(self.description_file))
            meters_per_unit = float(UsdGeom.GetStageMetersPerUnit(stage))
            y_up = UsdGeom.GetStageUpAxis(stage) == "Y"
            xform_cache = UsdGeom.XformCache(Usd.TimeCode.Default())
            # The non-mesh fallback (implicit gprims: planes, spheres, …):
            # the same purpose set the parser's bound consumers use.
            bbox_cache = UsdGeom.BBoxCache(
                Usd.TimeCode.Default(), ["default", "render"], useExtentsHint=True
            )
            lows: List[np.ndarray] = []
            highs: List[np.ndarray] = []

            def _matrix_to_numpy(matrix) -> np.ndarray:
                # pxr Gf.Matrix4d (row-vector convention, translation on the
                # bottom row) → column convention, mirroring
                # genesis.utils.usd.UsdContext.compute_transform's transpose.
                return np.array(
                    [[matrix[i][j] for j in range(4)] for i in range(4)],
                    dtype=np.float64,
                ).T

            # Entity prims, children pruned — find_all_rigid_entities' walk.
            entity_prims: List["Usd.Prim"] = []
            stage_iter = iter(Usd.PrimRange(stage.GetPseudoRoot()))
            for prim in stage_iter:
                if (
                    prim.HasAPI(UsdPhysics.ArticulationRootAPI)
                    or prim.HasAPI(UsdPhysics.RigidBodyAPI)
                    or prim.HasAPI(UsdPhysics.CollisionAPI)
                ):
                    entity_prims.append(prim)
                    stage_iter.PruneChildren()

            for entity in entity_prims:
                for prim in Usd.PrimRange(entity, Usd.TraverseInstanceProxies()):
                    if not prim.IsA(UsdGeom.Gprim):
                        continue
                    imageable = UsdGeom.Imageable(prim)
                    if str(imageable.ComputeVisibility()) == "invisible":
                        continue  # not parsed (usd_geometry's is_visible)
                    if str(imageable.ComputePurpose()) == "guide":
                        continue  # not parsed (usd_geometry's is_guide)
                    if prim.IsA(UsdGeom.Mesh):
                        points = UsdGeom.Mesh(prim).GetPointsAttr().Get()
                        if points is None or len(points) == 0:
                            continue
                        array = np.asarray(points, dtype=np.float64).reshape(-1, 3)
                        if not np.isfinite(array).all():
                            continue
                        matrix = _matrix_to_numpy(
                            xform_cache.GetLocalToWorldTransform(prim)
                        )
                        world = array @ matrix[:3, :3].T + matrix[:3, 3]
                        if not np.isfinite(world).all():
                            continue
                        lows.append(world.min(axis=0))
                        highs.append(world.max(axis=0))
                    else:
                        bound = bbox_cache.ComputeWorldBound(prim).ComputeAlignedRange()
                        if bound.IsEmpty():
                            continue
                        lows.append(np.asarray(bound.GetMin(), dtype=np.float64))
                        highs.append(np.asarray(bound.GetMax(), dtype=np.float64))
            if not lows:
                raise ValueError(
                    f"LightwheelEnv {self.object_id!r}: stage "
                    f"{self.description_file} has no drawable bounds."
                )
            low = np.min(lows, axis=0) * meters_per_unit
            high = np.max(highs, axis=0) * meters_per_unit
            if y_up:
                # Map the Y-up stage onto the Z-up Genesis world — the same
                # pre-multiply compute_transform applies to the entity pose.
                frame = _USD_Y_UP_TRANSFORM
                low, high = frame[:3, :3] @ low + frame[:3, 3], frame[:3, :3] @ high + frame[:3, 3]
            scale = self._morph_scale
            self._local_bbox_cache = make_bbox(
                torch.from_numpy(np.minimum(low, high) * scale),
                torch.from_numpy(np.maximum(low, high) * scale),
            )
        return self._local_bbox_cache

    # ------------------------------------------------------------------
    # Scene loading (add_stage)
    # ------------------------------------------------------------------

    def load_into_scene(
        self,
        world: "GenesisWorld",
        pos=(0.0, 0.0, 0.0),
        quat=(1.0, 0.0, 0.0, 0.0),
        name_override=None,
        batch_fixed_verts=False,
    ):
        """Load the environment stage into the scene (``gs.morphs.USD``).

        Returns the list of entities ``scene.add_stage`` produced (no count
        assertion — see the class docstring).
        """
        import genesis as gs

        # Patch Genesis's z3 collision-bitmask synthesis before the USD is
        # parsed: dense FilteredPairsAPI / contact-exclude assets otherwise
        # spin z3 for minutes per parse.  The constructive fast path solves
        # them in milliseconds (idempotent, no-op without z3).
        from unienv_genesis_collection import genesis_compat

        genesis_compat.install()

        self._ensure_assets()
        if name_override is not None:
            logger.warning(
                "LightwheelEnv %r: name_override=%r is ignored — "
                "scene.add_stage does not take an entity name; entities are "
                "named after the USD root prim.",
                self.name,
                name_override,
            )
        morph = gs.morphs.USD(
            file=str(self.description_file),
            scale=self._morph_scale,
            pos=pos,
            quat=quat,
            fixed=self.fixed,
            batch_fixed_verts=batch_fixed_verts,
        )
        # Room-scale SDF cells: the default ``Rigid()`` targets tabletop
        # manipulation props (5 mm cells / up to 128³ grids per collider), and
        # a scene stage splits into hundreds-to-thousands of prop colliders,
        # which overflows the solver's int32 SDF-GPU layout ("SDF Gradient
        # shape (n_cells=…) is too large" — Apartment's 5436 colliders sum to
        # ~10¹⁰ default-grid cells, 22× the int32 budget).  15 cm cells (with
        # a 96³ per-collider cap and the loader's own thin-wall refinement
        # shrinking to 2 cells across watertight walls) keep every observed
        # stage buildable while bounding the layout to ~10⁸ cells.
        material = gs.materials.Rigid(sdf_cell_size=0.15, sdf_max_res=96)
        return world.scene.add_stage(morph, material=material)


