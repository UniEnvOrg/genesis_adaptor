"""Lightwheel SimReady (open bundle) **static environments** as object descriptors.

The Lightwheel AI open-source bundle (`LightwheelAI/Lightwheel-simready-asset
<https://github.com/LightwheelAI/Lightwheel-simready-asset>`_) also ships a
``Locomotion/`` subset: jointless scene stages (terrains, rooms, staircases)
that are walked on rather than manipulated.  The collection hosts them on its
Hugging Face assets repo under ``objects/lightwheel_env/<object_id>/``, one
self-contained directory per scene::

    objects/lightwheel_env/lightwheel_env_grass/lightwheel_env_grass.usd
    objects/lightwheel_env/lightwheel_env_grass/草坪草地3D模型/...   # referenced payload

Why a **separate family** from
:class:`~unienv_genesis_collection.objects.hub_objects.articulated.lightwheel_furniture.LightwheelFurniture`:
the ``Manipulation`` tree's catalog semantics are per-object furniture, its
descriptor asserts a single articulated entity and its gate requires moving
joints.  A static environment violates all three (7 of the 8 Locomotion
categories have **zero** joints and zero ``RigidBodyAPI`` — they are
UE-exported visual+collision stages), and
:func:`~unienv_genesis_collection.objects.articulated_object.usd_link_meshes_at_config`
returns an empty mapping for them, which breaks the articulated descriptor's
geometry path outright.

Geometry: ``trimesh`` cannot read ``.usd`` (``NotImplementedError: file_type
'usd' not supported``), and these stages reach 439 MB / 1764 meshes, so
:meth:`LightwheelEnv.get_local_bounding_box` walks the pxr stage offline and
unions the **point-accurate world bounds of exactly the geometry
``scene.add_stage`` instantiates** — the collider/entity subtrees (see the
method's docstring).  A plain ``UsdGeom.BBoxCache`` union over the
pseudo-root children over-approximates in both directions: authored
``extent`` boxes are transformed rigidly (a rotated thin/diagonal mesh
inflates), and visual-only subtrees outside any collider are counted even
though ``add_stage`` never instantiates them — the Grass terrain lost
0.14 m in Z and the 2-storey staircase 20 m in X/Y to that before the
point-accurate walk.

The catalog ships with the assets as ``objects/lightwheel_env/catalog.json``
(generated by ``scripts/prepare_lightwheel_assets.py --subset locomotion``).

**License — CC BY-NC 4.0 (non-commercial).**  Same bundle, same terms as the
``Manipulation`` subset: the bundle README states "Creative Commons
Attribution-NonCommercial 4.0 International" ("Free for non-commercial use")
and requires the ``lightwheel_{asset_name}`` naming format for attribution —
hence the ``lightwheel_env_``-prefixed object ids.  The non-commercial clause
is accepted by the collection maintainer and flagged in
``docs/articulated_rooms.md`` (mirroring the ReplicaCAD caveat).

Typical usage::

    from unienv_genesis_collection.objects import LightwheelEnv, make_lightwheel_env_pool

    terrain = LightwheelEnv("lightwheel_env_grass")
    pool = make_lightwheel_env_pool(tags="terrain", n=2,
                                    rng=torch.Generator().manual_seed(0))
"""

