"""Google Scanned Objects (GSO) as :class:`ManipulatableObject` descriptors.

The assets are a repackaged copy of `kevinzakka/mujoco_scanned_objects
<https://github.com/kevinzakka/mujoco_scanned_objects>`_ — MJCF models for
all 1030 objects of Google's `Scanned Objects dataset
<https://arxiv.org/abs/2204.11918>`_ (meshes/textures CC-BY 4.0, MJCF MIT)
— hosted on the collection's Hugging Face assets repo under
``objects/gso/<object_id>/``.  Each object directory is self-contained::

    objects/gso/3D_Dollhouse_Lamp/model.xml            # upstream MJCF (welded body)
    objects/gso/3D_Dollhouse_Lamp/model_freejoint.xml  # + injected <freejoint/>
    objects/gso/3D_Dollhouse_Lamp/model.obj            # visual mesh
    objects/gso/3D_Dollhouse_Lamp/texture.png
    objects/gso/3D_Dollhouse_Lamp/model_collision_*.obj  # V-HACD pieces

The upstream ``model.xml`` has no joint, so its body is welded to the world;
``scripts/prepare_gso_assets.py`` generates the ``model_freejoint.xml``
variant that :class:`GSOObject` loads for movable (``fixed=False``) objects.
Genesis's ``gs.morphs.MJCF`` is used for loading, so the V-HACD collision
decomposition and the MJCF-bound texture are used as-is.

The dataset ships no real masses: Genesis derives each object's mass from its
geometry at a fixed material density, which is 10–100× the real product weight
(a scanned plush bib comes out at ~3.8 kg, a LEGO advent calendar at ~13.5 kg)
and destabilises contact physics.  :class:`GSOObject` therefore always
overrides the derived mass (see :meth:`GSOObject.apply_mass`):

* an explicit ``mass=`` argument, else
* :data:`GSO_MASSES` — curated real-world weights for the objects the clutter
  pools use most, else
* :data:`GSO_MASS_DENSITY` kg/m³ applied to the collision-hull volume, i.e. a
  plausible density for hollow scanned household objects, clamped to
  :data:`GSO_MASS_BOUNDS`.

Per-object metadata is generated, not hand-curated: language annotations span
broad category terms (from the category labels of the original dataset's
metadata on Gazebo Fuel) to the detailed product description, and the tags
carry those same categories — in separate fields, mirroring YCB.  The
metadata ships with the assets as ``objects/gso/catalog.json``.

Typical usage::

    from unienv_genesis_collection.objects import GSOObject, make_gso_pool

    lamp = GSOObject("3D_Dollhouse_Lamp")
    heavy = GSOObject("Cole_Hardware_Hammer_Black", mass=0.45)
    pool = make_gso_pool(tags="shoe", n=5,
                         rng=torch.Generator().manual_seed(0))
"""

