def get_gso_catalog() -> Dict[str, ObjectInfo]:
    """Return the GSO catalog (object id → :class:`ObjectInfo`).

    Loaded from ``objects/gso/catalog.json`` in the assets folder
    (downloaded on first use) and cached.  Annotations are ordered from
    broad category terms to the detailed product description; tags carry
    the upstream category labels (e.g. ``"shoe"``, ``"toys"``,
    ``"consumer_goods"``) and may be empty — not every object is
    categorised upstream.
    """
    return load_catalog(GSO_CATALOG_PATH)


def list_gso_objects(
    *,
    tags: Optional[Union[str, Iterable[str]]] = None,
    contains: Optional[str] = None,
) -> List[str]:
    """Return GSO object ids, optionally filtered by tags and/or substring.

    Works fully offline — only the generated catalog is consulted.

    Args:
        tags: A tag or iterable of tags.  Only objects carrying **all** of
            them are returned (e.g. ``"shoe"``, ``"toys"``).
        contains: Case-insensitive substring to filter ids by (e.g.
            ``"lamp"``).  Combinable with *tags*.

    Returns:
        Sorted list of object ids.
    """
    if tags is None:
        wanted: FrozenSet[str] = frozenset()
    elif isinstance(tags, str):
        wanted = frozenset((tags,))
    else:
        wanted = frozenset(tags)
    needle = contains.lower() if contains is not None else None
    return [
        object_id
        for object_id, info in get_gso_catalog().items()
        if wanted <= info.tags
        and (needle is None or needle in object_id.lower())
    ]


