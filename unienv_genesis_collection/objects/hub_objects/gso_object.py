"""Google Scanned Objects (GSO) as :class:`ManipulatableObject` descriptors.

The assets are a repackaged copy of `kevinzakka/mujoco_scanned_objects
<https://github.com/kevinzakka/mujoco_scanned_objects>`_ — MJCF models for
all 1030 objects of Google's `Scanned Objects dataset
<https://arxiv.org/abs/2204.11918>`_ (meshes/textures CC-BY 4.0, MJCF MIT)
— hosted on the collection's Hugging Face assets repo under
``objects/gso/<object_id>/``.  Each object directory is self-contained::

    objects/gso/3D_Dollhouse_Lamp/model.xml            # upstream MJCF (welded body)
    objects/gso/3D_Dollhouse_Lamp/model_freejoint.xml  # + injected <freejoint/>
    objects/gso/3D_Dollhouse_Lamp/model.obj            # visual mesh
    objects/gso/3D_Dollhouse_Lamp/texture.png
    objects/gso/3D_Dollhouse_Lamp/model_collision_*.obj  # V-HACD pieces

The upstream ``model.xml`` has no joint, so its body is welded to the world;
``scripts/prepare_gso_assets.py`` generates the ``model_freejoint.xml``
variant that :class:`GSOObject` loads for movable (``fixed=False``) objects.
Genesis's ``gs.morphs.MJCF`` is used for loading, so the V-HACD collision
decomposition and the MJCF-bound texture are used as-is.

Unlike YCB, the dataset ships no real masses — Genesis derives mass from the
collision geometry and material density.  Per-object metadata is generated,
not hand-curated: language annotations span broad category terms (from the
category labels of the original dataset's metadata on Gazebo Fuel) to the
detailed product description, and the tags carry those same categories —
in separate fields, mirroring YCB.  The metadata ships with the assets as
``objects/gso/catalog.json``.

Typical usage::

    from unienv_genesis_collection.objects import GSOObject, make_gso_pool

    lamp = GSOObject("3D_Dollhouse_Lamp")
    pool = make_gso_pool(tags="shoe", n=5,
                         rng=torch.Generator().manual_seed(0))
"""

from __future__ import annotations

from pathlib import Path
from typing import (
    Dict,
    FrozenSet,
    Iterable,
    List,
    Optional,
    Sequence,
    Tuple,
    Union,
    TYPE_CHECKING,
)

import torch

from unienv_genesis_collection.objects.hub_objects.catalog import (
    ObjectInfo,
    load_catalog,
)
from unienv_genesis_collection.objects.hub_objects.hub_asset_object import (
    HubAssetMeshObject,
    xml_file_references,
)

if TYPE_CHECKING:
    from unienv_genesis.world.genesis_world import GenesisWorld

__all__ = [
    "GSO_ASSETS_ROOT",
    "GSO_CATALOG_PATH",
    "get_gso_catalog",
    "GSOObject",
    "list_gso_objects",
    "make_gso_pool",
]

# Path of the GSO collection relative to the assets root (POSIX separators).
GSO_ASSETS_ROOT = "objects/gso"

# The catalog (language annotations + tags per object) ships with the assets
# as ``objects/gso/catalog.json``; it is generated by
# ``scripts/prepare_gso_assets.py`` from the dataset's Gazebo Fuel metadata.
GSO_CATALOG_PATH = f"{GSO_ASSETS_ROOT}/catalog.json"


def get_gso_catalog() -> Dict[str, ObjectInfo]:
    """Return the GSO catalog (object id → :class:`ObjectInfo`).

    Loaded from ``objects/gso/catalog.json`` in the assets folder
    (downloaded on first use) and cached.  Annotations are ordered from
    broad category terms to the detailed product description; tags carry
    the upstream category labels (e.g. ``"shoe"``, ``"toys"``,
    ``"consumer_goods"``) and may be empty — not every object is
    categorised upstream.
    """
    return load_catalog(GSO_CATALOG_PATH)


def list_gso_objects(
    *,
    tags: Optional[Union[str, Iterable[str]]] = None,
    contains: Optional[str] = None,
) -> List[str]:
    """Return GSO object ids, optionally filtered by tags and/or substring.

    Works fully offline — only the generated catalog is consulted.

    Args:
        tags: A tag or iterable of tags.  Only objects carrying **all** of
            them are returned (e.g. ``"shoe"``, ``"toys"``).
        contains: Case-insensitive substring to filter ids by (e.g.
            ``"lamp"``).  Combinable with *tags*.

    Returns:
        Sorted list of object ids.
    """
    if tags is None:
        wanted: FrozenSet[str] = frozenset()
    elif isinstance(tags, str):
        wanted = frozenset((tags,))
    else:
        wanted = frozenset(tags)
    needle = contains.lower() if contains is not None else None
    return [
        object_id
        for object_id, info in get_gso_catalog().items()
        if wanted <= info.tags
        and (needle is None or needle in object_id.lower())
    ]


# ---------------------------------------------------------------------------
# GSOObject
# ---------------------------------------------------------------------------

class GSOObject(HubAssetMeshObject):
    """A Google Scanned Object loaded into Genesis via its MJCF model.

    Inherits the trimesh-based bounding-box and grasp-candidate machinery
    from :class:`MeshObject` (pointed at the object's ``model.obj``), but
    overrides :meth:`load_into_scene` to load the MJCF so Genesis uses the
    precomputed V-HACD collision pieces and the texture bound by the MJCF
    material.

    Movable objects load the prepared ``model_freejoint.xml``; ``fixed=True``
    objects load the pristine upstream ``model.xml``, whose jointless body is
    welded to the world.

    Construction is offline-safe; assets are downloaded lazily on first
    scene load or geometry query and verified for completeness.

    Args:
        object_id: Object id, e.g. ``"3D_Dollhouse_Lamp"``.  See
            :func:`get_gso_catalog` or :func:`list_gso_objects`.
        scale: Uniform scale factor.  MJCF morphs do not support per-axis
            scaling.
        name: Technical identifier; defaults to *object_id*.
        fixed: Whether the object is immovable.
        language_annotations: Override the catalog's default annotation.
    """

    def __init__(
        self,
        object_id: str,
        scale: float = 1.0,
        name: Optional[str] = None,
        fixed: bool = False,
        language_annotations: Optional[Sequence[str]] = None,
    ):
        catalog = get_gso_catalog()
        info = catalog.get(object_id)
        if info is None:
            raise KeyError(
                f"Unknown GSO object id: {object_id!r}. "
                f"See list_gso_objects() for the {len(catalog)} available ids."
            )
        if isinstance(scale, tuple):
            raise ValueError(
                "GSOObject only supports uniform (scalar) scaling: "
                "anisotropic scaling is not supported by MJCF morphs."
            )
        super().__init__(
            asset_relative_dir=f"{GSO_ASSETS_ROOT}/{object_id}",
            mesh_file_name="model.obj",
            scale=scale,
            name=name or object_id,
            fixed=fixed,
            language_annotations=(
                language_annotations
                if language_annotations is not None
                else info.language_annotations
            ),
        )
        self.object_id = object_id
        self.info = info
        self.mjcf_file = self.asset_dir / (
            "model.xml" if fixed else "model_freejoint.xml"
        )
        self._morph_scale = float(scale)

    def _required_files(self) -> List[Path]:
        """Both MJCF variants, the visual mesh + texture, and every mesh
        referenced by the MJCF (the number of V-HACD pieces varies)."""
        required = [
            self.asset_dir / "model.xml",
            self.asset_dir / "model_freejoint.xml",
            self.asset_dir / "model.obj",
            self.asset_dir / "texture.png",
        ]
        if self.mjcf_file.is_file():
            required += [
                self.asset_dir / ref
                for ref in xml_file_references(self.mjcf_file, attribute="file")
            ]
        return required

    def load_into_scene(
        self,
        world: "GenesisWorld",
        pos=(0.0, 0.0, 0.0),
        quat=(1.0, 0.0, 0.0, 0.0),
        name_override=None,
        batch_fixed_verts=False,
    ):
        import genesis as gs

        self._ensure_assets()
        morph = gs.morphs.MJCF(
            file=str(self.mjcf_file),
            scale=self._morph_scale,
            pos=pos,
            quat=quat,
            batch_fixed_verts=batch_fixed_verts,
            requires_jac_and_IK=False,
        )
        # No surface override: Default() preserves the MJCF-bound texture.
        return world.scene.add_entity(
            morph,
            name=name_override or self.name,
        )


# ---------------------------------------------------------------------------
# Pool building
# ---------------------------------------------------------------------------

def make_gso_pool(
    object_ids: Optional[Sequence[str]] = None,
    *,
    tags: Optional[Union[str, Iterable[str]]] = None,
    contains: Optional[str] = None,
    n: Optional[int] = None,
    rng: Optional[torch.Generator] = None,
    **object_kwargs,
) -> List[GSOObject]:
    """Build a list of :class:`GSOObject` for use as an object pool.

    The result plugs directly into consumers such as
    ``ClutteredTableManager(object_pool=...)``.  Construction does not
    download anything; assets are fetched when the objects are first
    loaded into a scene.

    Args:
        object_ids: Explicit ids to use (order preserved).  Mutually
            exclusive with *tags* / *contains*.
        tags: Filter the catalog by category tags (see
            :func:`list_gso_objects`).
        contains: Filter ids by case-insensitive substring (see
            :func:`list_gso_objects`).  Combinable with *tags*.
        n: If given, sample *n* distinct objects from the selection.
        rng: Optional :class:`torch.Generator` for reproducible sampling.
        **object_kwargs: Forwarded to every :class:`GSOObject` (e.g.
            ``scale=0.8``).

    Returns:
        List of :class:`GSOObject` descriptors with unique names.

    Raises:
        ValueError: If *object_ids* is combined with *tags* / *contains*,
            or *n* exceeds the number of selected objects.
        KeyError: If an explicit id is not in the catalog.
    """
    if object_ids is not None and (tags is not None or contains is not None):
        raise ValueError("Pass either object_ids or tags/contains, not both.")

    ids = (
        list(object_ids)
        if object_ids is not None
        else list_gso_objects(tags=tags, contains=contains)
    )

    if n is not None:
        if n > len(ids):
            raise ValueError(
                f"Requested {n} objects but only {len(ids)} match the selection."
            )
        perm = torch.randperm(len(ids), generator=rng)[:n].tolist()
        ids = [ids[i] for i in perm]

    return [GSOObject(object_id, **object_kwargs) for object_id in ids]
