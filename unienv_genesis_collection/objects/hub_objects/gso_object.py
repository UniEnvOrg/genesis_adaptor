class GSOObject(HubAssetMeshObject):
    """A Google Scanned Object loaded into Genesis via its MJCF model.

    Inherits the trimesh-based grasp-candidate machinery from
    :class:`MeshObject` (pointed at the object's ``model.obj``), but
    overrides :meth:`get_local_bounding_box` and :meth:`load_into_scene` so
    placement and simulation use the MJCF's precomputed V-HACD collision
    pieces while rendering keeps the texture bound by the MJCF material.

    Movable objects load the prepared ``model_freejoint.xml``; ``fixed=True``
    objects load the pristine upstream ``model.xml``, whose jointless body is
    welded to the world.

    The mass Genesis derives from the asset's geometry (see the module
    docstring) is always replaced by a realistic one — an explicit *mass*, a
    curated entry in :data:`GSO_MASSES`, or the :data:`GSO_MASS_DENSITY`
    fallback — applied by :meth:`apply_mass` once the scene is built.

    Construction is offline-safe; assets are downloaded lazily on first
    scene load or geometry query and verified for completeness.

    Args:
        object_id: Object id, e.g. ``"3D_Dollhouse_Lamp"``.  See
            :func:`get_gso_catalog` or :func:`list_gso_objects`.
        scale: Uniform scale factor.  MJCF morphs do not support per-axis
            scaling.
        name: Technical identifier; defaults to *object_id*.
        fixed: Whether the object is immovable.
        language_annotations: Override the catalog's default annotation.
        mass: Explicit total mass in **kg**, overriding both the curated
            :data:`GSO_MASSES` entry and the density fallback.  Use this to
            pin a task's object to a known weight.
    """

    def __init__(
        self,
        object_id: str,
        scale: float = 1.0,
        name: Optional[str] = None,
        fixed: bool = False,
        language_annotations: Optional[Sequence[str]] = None,
        standing_quaternion: Optional[Sequence[float]] = None,
        mass: Optional[float] = None,
    ):
        catalog = get_gso_catalog()
        info = catalog.get(object_id)
        if info is None:
            raise KeyError(
                f"Unknown GSO object id: {object_id!r}. "
                f"See list_gso_objects() for the {len(catalog)} available ids."
            )
        if isinstance(scale, tuple):
            raise ValueError(
                "GSOObject only supports uniform (scalar) scaling: "
                "anisotropic scaling is not supported by MJCF morphs."
            )
        super().__init__(
            asset_relative_dir=f"{GSO_ASSETS_ROOT}/{object_id}",
            mesh_file_name="model.obj",
            scale=scale,
            name=name or object_id,
            fixed=fixed,
            language_annotations=(
                language_annotations
                if language_annotations is not None
                else info.language_annotations
            ),
            visual_texture_file_name="texture.png",
            standing_quaternion=(
                standing_quaternion
                if standing_quaternion is not None
                else info.standing_quaternion
            ),
            mass=mass,
        )
        self.object_id = object_id
        self.info = info
        self.mjcf_file = self.asset_dir / (
            "model.xml" if fixed else "model_freejoint.xml"
        )
        self._morph_scale = float(scale)
        self._collision_trimesh_cache = None

    def _required_files(self) -> List[Path]:
        """Both MJCF variants, the visual mesh + texture, and every mesh
        referenced by the MJCF (the number of V-HACD pieces varies)."""
        required = [
            self.asset_dir / "model.xml",
            self.asset_dir / "model_freejoint.xml",
            self.asset_dir / "model.obj",
            self.asset_dir / "texture.png",
        ]
        if self.mjcf_file.is_file():
            required += [
                self.asset_dir / ref
                for ref in xml_file_references(self.mjcf_file, attribute="file")
            ]
        return required

    def _load_collision_trimesh(self):
        """Load and cache the union of the collision meshes.

        GSO objects are simulated from the MJCF's V-HACD collision pieces, so
        placement should use those bounds rather than the visual mesh bounds.
        """
        if self._collision_trimesh_cache is None:
            import trimesh

            self._ensure_assets()
            root = xml_file_references(self.mjcf_file, attribute="file")
            collision_files = [
                self.asset_dir / ref
                for ref in root
                if Path(ref).name.startswith("model_collision_")
            ]
            if not collision_files:
                self._collision_trimesh_cache = self._load_trimesh()
                return self._collision_trimesh_cache

            meshes = [
                trimesh.load(collision_file, force="mesh")
                for collision_file in collision_files
            ]
            if len(meshes) == 1:
                mesh = meshes[0]
            else:
                mesh = trimesh.util.concatenate(meshes)
            mesh.apply_scale(self.scale)
            self._collision_trimesh_cache = mesh
        return self._collision_trimesh_cache

    def get_local_bounding_box(self):
        collision_mesh = self._load_collision_trimesh()
        return make_bbox(
            torch.from_numpy(collision_mesh.bounds[0].copy()),
            torch.from_numpy(collision_mesh.bounds[1].copy()),
        )

    # ------------------------------------------------------------------
    # Mass
    # ------------------------------------------------------------------

    def resolve_mass(self) -> float:
        """Return the realistic mass (kg) this object should simulate with.

        Resolution order: the explicit ``mass=`` argument, the curated
        :data:`GSO_MASSES` entry, then the :data:`GSO_MASS_DENSITY` fallback
        on the collision-hull volume (clamped to :data:`GSO_MASS_BOUNDS`).

        The fallback needs the object's assets (it reads the collision hull),
        so it is downloaded on first use here rather than at construction.
        """
        if self.mass is not None:
            return self.mass
        curated = GSO_MASSES.get(self.object_id)
        if curated is not None:
            return float(curated)
        volume = float(self._load_collision_trimesh().volume)
        low, high = GSO_MASS_BOUNDS
        return float(min(max(volume * GSO_MASS_DENSITY, low), high))

    def apply_mass(self, entity) -> None:
        """Set the built entity's total mass to :meth:`resolve_mass` (kg).

        Genesis derives the mass of an MJCF morph from its geometry, which for
        these scanned assets is 10–100× the real product weight (a plush bib
        comes out at ~3.8 kg, a LEGO advent calendar at ~13.5 kg) and makes
        contact physics pop and grasped objects slip.  ``entity.set_mass``
        replaces it exactly, rescaling the inertia of every link by the same
        factor.  Called by scene-assembly nodes after the scene is built.
        """
        if self.fixed:
            # A welded body moves no mass, so ``set_mass`` would raise.
            return
        entity.set_mass(self.resolve_mass())

    def load_into_scene(
        self,
        world: "GenesisWorld",
        pos=(0.0, 0.0, 0.0),
        quat=(1.0, 0.0, 0.0, 0.0),
        name_override=None,
        batch_fixed_verts=False,
    ):
        import genesis as gs

        self._ensure_assets()
        morph = gs.morphs.MJCF(
            file=str(self.mjcf_file),
            scale=self._morph_scale,
            pos=pos,
            quat=quat,
            align=False,
            batch_fixed_verts=batch_fixed_verts,
            requires_jac_and_IK=False,
        )
        # Bind the MJCF-referenced texture explicitly.  Genesis's rasterizer
        # reads the material out of the parsed MJCF either way, but a renderer
        # that re-exports the scene (Nyx, UniFlow's default camera backend)
        # serializes an MJCF entity's visual mesh from memory into a shared
        # export folder: every textured mesh writes the same generic
        # ``material.mtl``/``material_0.png`` pair there, so all GSO objects of
        # a scene end up sharing one (the last-written) texture and render
        # untextured.  An explicit ``ImageTexture`` surface is exported as a
        # per-instance albedo-texture override pointing at this object's own
        # ``texture.png``, which keeps every object's texture intact.
        #
        # WORKAROUND for upstream bug — multiple textured MJCF entities in one
        # scene share/overwrite each other's albedo texture:
        #   https://github.com/Genesis-Embodied-AI/genesis-nyx/issues/22
        # TODO: once that issue is fixed and released, this explicit surface can
        # be dropped (Genesis's default MJCF material binding suffices then).
        surface = gs.surfaces.Plastic(
            diffuse_texture=gs.textures.ImageTexture(
                image_path=self.visual_texture_path,
            ),
        )
        return world.scene.add_entity(
            morph,
            surface=surface,
            name=name_override or self.name,
        )


